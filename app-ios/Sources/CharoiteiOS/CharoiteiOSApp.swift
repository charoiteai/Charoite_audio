import ActivityKit
import SwiftUI

@main
struct CharoiteiOSApp: App {
    /// Плашки, пережившие смерть приложения, — снимок ДО того, как экран
    /// записи успеет завести новую: автостарт (№167) может создать Live
    /// Activity раньше, чем асинхронная уборка дойдёт до `activities`, и
    /// уборка по живому списку гасила бы свежую плашку.
    private let staleActivities: [Activity<RecordActivityAttributes>]

    init() {
        // Приложение только что стартовало — значит, никакая запись сейчас
        // идти не может. Всё, что осталось от прошлого запуска, — следы
        // аварии, и с ними надо разобраться ДО первой записи.
        //
        // Файл недописанной записи — в очередь, чтобы записанное до сбоя
        // всё-таки уехало на Mac. Синхронно и здесь, а не в `.task`: с
        // автостартом запись начинается сразу после появления экрана, и
        // уборка, пришедшая позже, утащила бы в очередь ИДУЩИЙ файл.
        Inbox.rescueOrphans()
        staleActivities = Activity<RecordActivityAttributes>.activities
    }

    var body: some Scene {
        WindowGroup {
            RootView()
                .task {
                    // Плашка на локскрине, пережившая смерть приложения,
                    // показывала бегущий таймер несуществующей записи —
                    // интерфейс, который активно врёт, хуже отсутствующего.
                    for a in staleActivities {
                        await a.end(nil, dismissalPolicy: .immediate)
                    }
                }
        }
    }
}
