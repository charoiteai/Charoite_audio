    assert g._same_fingerprint(g._fingerprint(a), g._fingerprint(b)) is same
    assert g._same_fingerprint(g._fingerprint(b), g._fingerprint(a)) is same
    assert (len(g._merge_decisions([a, b])[0]) == 1) is same


