"""Опознанное имя — не догадка. Чем платит человек за ошибку атрибуции.

Имя, поставленное неверно, не остаётся в стенограмме: `rename_speaker`
переписывает метку ЗАДНИМ ЧИСЛОМ во всех блоках встречи (src/main.py:171),
дальше минутки, поручения и граф наследуют её без всякого сомнения. Поручение
уходит не тому, узел графа склеивает двух разных людей. Поэтому цена ошибки
здесь выше, чем цена пропущенного имени: «Собеседник 2» честен, а неверное имя
врёт молча.

Отсюда два требования, которые этот файл держит.

ПЕРВОЕ: имя владельца никогда не достаётся собеседнику. Проверка в daemon.py
сравнивала предложенное имя с `sufler.user_name` ЦЕЛИКОМ, а config.example и
SETUP просят там «ваше имя» — человек пишет имя и фамилию. Тогда «Игорь» не
равно «Игорь Ветров», проверка пропускает, и реплика собеседника «Игорь,
привет, ты смету смотрел?» подписывает всю его половину встречи именем
владельца.

ВТОРОЕ: правило «обращение — это не говорящий» работает в ОБЕИХ ветках
опознания. Гвард против «Саш, ну а кто…» (метка получала имя Саша) стоял только
в мультиспикерной ветке, где есть модель голосов. Одиночная ветка — та, что
работает БЕЗ модели диаризации, то есть у каждого, кто только что поставил
продукт, — обходилась одним промптом к лёгкой модели.

Имена в тестах — из встроенного демо-графа (demo/graph), чтобы файл не тащил
ничьих настоящих.
"""
import pathlib
import sys

SRC = pathlib.Path(__file__).resolve().parent.parent / "src"
sys.path.insert(0, str(SRC))

from speaker_names import is_counterpart, trustworthy_name  # noqa: E402


def test_мгновенные_ответы_не_гаснут_после_опознания_имени():
    """Гейт ⚡ — «не владелец», а не «метка начинается с Собеседник».

    Как только name_loop опознавал собеседника («Собеседник 1» → имя),
    прежний гейт в демоне гас, и мгновенные ответы для этого человека
    умирали до конца встречи (аудит 14.08).
    """
    assert is_counterpart("Собеседник 1", "Игорь Ветров")
    assert is_counterpart("Полина", "Игорь Ветров"), \
        "опознанный собеседник перестал считаться «той стороной»"


def test_владелец_не_считается_той_стороной():
    assert not is_counterpart("Игорь", "Игорь Ветров")
    assert not is_counterpart("Игорь Ветров", "Игорь Ветров")
    assert not is_counterpart("", "Игорь Ветров"), "пустая метка — не вопрос"


def test_без_имени_владельца_гейт_открыт_для_всех():
    """user_name не настроен — отсечь владельца не по чему: лучше лишняя
    подсказка у свежей установки, чем мёртвые ⚡."""
    assert is_counterpart("Собеседник 1", "")

OWNER = "Игорь Ветров"

# Формат хвоста стенограммы — «[ЧЧ:ММ] метка: текст» (src/main.py:216).
DIALOG = "\n".join((
    "[10:01] Я: Привет, начнём?",
    "[10:01] Собеседник: Игорь, привет, ты смету смотрел?",
    "[10:02] Собеседник: Там по срокам всё сдвинулось на неделю.",
))

INTRO = "\n".join((
    "[10:00] Собеседник: Это Мария, добрый день.",
    "[10:00] Я: Добрый, слушаю.",
))

ADDRESSED = "\n".join((
    "[10:00] Я: Мария, привет — расскажешь про каталог?",
    "[10:01] Собеседник: Да, конечно, сейчас.",
))


def test_owner_first_name_never_becomes_a_participant():
    """Р1: «Игорь» и «Игорь Ветров» — один человек, и это владелец."""
    assert trustworthy_name("Игорь", sample=DIALOG, label="Собеседник",
                            owner_name=OWNER) is None


def test_owner_diminutive_is_refused_too():
    """«Игорёк» отличается от «Игорь» окончанием — так же, как «Полин» от
    «Полина», которое код уже умеет склеивать. Правило одно, знак разный."""
    assert trustworthy_name("Игорёк", sample=DIALOG.replace("Игорь", "Игорёк"),
                            label="Собеседник", owner_name=OWNER) is None


def test_address_inside_own_line_is_not_the_speaker():
    """Р2: имя звучит только в репликах самой метки и это не представление.

    Ровно случай «Саш, ну а кто…»: говорящий обращается к кому-то другому.
    Раньше гвард стоял только в мультиспикерной ветке.
    """
    sample = "\n".join((
        "[10:00] Собеседник: Мария, а ты смету видела?",
        "[10:01] Собеседник: Ладно, потом уточню.",
    ))
    assert trustworthy_name("Мария", sample=sample, label="Собеседник",
                            owner_name=OWNER) is None


def test_self_introduction_is_trusted():
    assert trustworthy_name("Мария", sample=INTRO, label="Собеседник",
                            owner_name=OWNER) == "Мария"


def test_name_heard_from_the_other_side_is_trusted():
    """Обращение в ЧУЖОЙ реплике — законный источник имени."""
    assert trustworthy_name("Мария", sample=ADDRESSED, label="Собеседник",
                            owner_name=OWNER) == "Мария"


def test_case_is_restored_from_known_people():
    """«Полин» → «Полина»: звательный падеж не должен попасть в граф."""
    sample = "[10:00] Я: Полин, привет.\n[10:01] Собеседник: Привет!"
    assert trustworthy_name("Полин", sample=sample, label="Собеседник",
                            owner_name=OWNER, known=("Полина", "Мария")) == "Полина"


def test_name_must_be_heard_in_the_transcript():
    """Модель может выдумать имя. В стенограмме его нет — значит нет."""
    assert trustworthy_name("Светлана", sample=ADDRESSED, label="Собеседник",
                            owner_name=OWNER) is None


def test_junk_is_refused():
    for raw in ("", "   ", "NONE", "none", "Ок", "Да", "42", "Собеседник",
                "МариятаженеСветлана"):
        assert trustworthy_name(raw, sample=INTRO, label="Собеседник",
                                owner_name=OWNER) is None, raw


def test_punctuation_and_case_are_normalised():
    assert trustworthy_name("«мария».", sample=INTRO, label="Собеседник",
                            owner_name=OWNER) == "Мария"


def test_empty_owner_name_does_not_open_the_gate():
    """Пустой user_name в конфиге — обычное дело: проверка владельца просто
    не срабатывает, остальные гварды обязаны работать по-прежнему."""
    assert trustworthy_name("Мария", sample=INTRO, label="Собеседник",
                            owner_name="") == "Мария"
    sample = "[10:00] Собеседник: Мария, а ты смету видела?"
    assert trustworthy_name("Мария", sample=sample, label="Собеседник",
                            owner_name="") is None


def test_метка_канала_владельца_закрывает_гейт_мгновенных_ответов():
    """Пока реплики владельца шли как «Собеседник N», гейт считал их чужими
    и ⚡ отвечала на вопросы самого хозяина встречи (ревью 19.08, DeepSeek).
    Подпись по каналу это закрывает — здесь проверяется обе формы метки:
    имя из настроек и «Я», когда имя не задано."""
    assert not is_counterpart("Игорь Ветров", "Игорь Ветров")
    assert is_counterpart("Собеседник 2", "Игорь Ветров"), \
        "а вот нейтральная метка по-прежнему считается той стороной"
    # Имя не задано: демон сверяет с меткой своего канала, иначе гейт
    # остаётся открытым на собственные вопросы (ревью 19.08).
    assert not is_counterpart("Я", "Я")
    assert is_counterpart("Я", ""), \
        "без опоры отсечь владельца нечем — демон и передаёт ему «Я»"


def test_метка_своего_канала_закрывает_гейт_любым_именем():
    """Гейт мгновенных ответов не должен зависеть от того, как названа
    метка: своя дорожка — это владелец по определению, а не догадка об
    имени. Сверка только по user_name ломалась дважды: при незаданном имени
    метка «Я» считалась чужой, а при имени, совпавшем с нейтральной меткой,
    захват подставлял «Я», и ⚡ снова отвечала на вопросы хозяина встречи
    (ревью 19.08, круги 4 и 7). Здесь закреплена сама сверка по имени;
    сверку по метке канала демон делает до неё."""
    assert not is_counterpart("Я", "Я")
    assert not is_counterpart("Игорь Ветров", "Игорь Ветров")
    assert is_counterpart("Собеседник 2", "Игорь Ветров")
