def test_мгновенные_ответы_не_гаснут_после_опознания_имени():
    """Гейт ⚡ — «не владелец», а не «метка начинается с Собеседник».

    Как только name_loop опознавал собеседника («Собеседник 1» → имя),
    прежний гейт в демоне гас, и мгновенные ответы для этого человека
    умирали до конца встречи (аудит 14.08).
    """
    assert is_counterpart("Собеседник 1", "Игорь Ветров")
    assert is_counterpart("Полина", "Игорь Ветров"), \
        "опознанный собеседник перестал считаться «той стороной»"


def test_владелец_не_считается_той_стороной():
    assert not is_counterpart("Игорь", "Игорь Ветров")
    assert not is_counterpart("Игорь Ветров", "Игорь Ветров")
    assert not is_counterpart("", "Игорь Ветров"), "пустая метка — не вопрос"


def test_без_имени_владельца_гейт_открыт_для_всех():
    """user_name не настроен — отсечь владельца не по чему: лучше лишняя
    подсказка у свежей установки, чем мёртвые ⚡."""
    assert is_counterpart("Собеседник 1", "")

OWNER = "Игорь Ветров"

# Формат хвоста стенограммы — «[ЧЧ:ММ] метка: текст» (src/main.py:216).
DIALOG = "\n".join((
    "[10:01] Я: Привет, начнём?",
    "[10:01] Собеседник: Игорь, привет, ты смету смотрел?",
    "[10:02] Собеседник: Там по срокам всё сдвинулось на неделю.",
))

INTRO = "\n".join((
    "[10:00] Собеседник: Это Мария, добрый день.",
    "[10:00] Я: Добрый, слушаю.",
))

ADDRESSED = "\n".join((
    "[10:00] Я: Мария, привет — расскажешь про каталог?",
    "[10:01] Собеседник: Да, конечно, сейчас.",
))


def test_owner_first_name_never_becomes_a_participant():
    """Р1: «Игорь» и «Игорь Ветров» — один человек, и это владелец."""
    assert trustworthy_name("Игорь", sample=DIALOG, label="Собеседник",
                            owner_name=OWNER) is None


def test_owner_diminutive_is_refused_too():
    """«Игорёк» отличается от «Игорь» окончанием — так же, как «Полин» от
    «Полина», которое код уже умеет склеивать. Правило одно, знак разный."""
    assert trustworthy_name("Игорёк", sample=DIALOG.replace("Игорь", "Игорёк"),
                            label="Собеседник", owner_name=OWNER) is None


def test_address_inside_own_line_is_not_the_speaker():
    """Р2: имя звучит только в репликах самой метки и это не представление.

    Ровно случай «Саш, ну а кто…»: говорящий обращается к кому-то другому.
    Раньше гвард стоял только в мультиспикерной ветке.
    """
    sample = "\n".join((
        "[10:00] Собеседник: Мария, а ты смету видела?",
        "[10:01] Собеседник: Ладно, потом уточню.",
    ))
    assert trustworthy_name("Мария", sample=sample, label="Собеседник",
                            owner_name=OWNER) is None


def test_self_introduction_is_trusted():
    assert trustworthy_name("Мария", sample=INTRO, label="Собеседник",
                            owner_name=OWNER) == "Мария"


def test_name_heard_from_the_other_side_is_trusted():
    """Обращение в ЧУЖОЙ реплике — законный источник имени."""
    assert trustworthy_name("Мария", sample=ADDRESSED, label="Собеседник",
                            owner_name=OWNER) == "Мария"


def test_case_is_restored_from_known_people():
    """«Полин» → «Полина»: звательный падеж не должен попасть в граф."""
    sample = "[10:00] Я: Полин, привет.\n[10:01] Собеседник: Привет!"
    assert trustworthy_name("Полин", sample=sample, label="Собеседник",
                            owner_name=OWNER, known=("Полина", "Мария")) == "Полина"


def test_vocative_resolves_to_known_person():
    """«Коль» → «Коля»: префиксная склейка это не видит — четвёртая буква разная.

    Встреча 05.09: Коля получил в графе второй узел «Коль» из обращения
    «Коль, ты имеешь в виду…». Обратный ход из звательного падежа идёт до
    префиксного и только к точному известному имени."""
    sample = "[10:00] Я: Коль, ты имеешь в виду уточнение?\n[10:01] Собеседник: Ну да."
    assert trustworthy_name("Коль", sample=sample, label="Собеседник",
                            owner_name=OWNER, known=("Коля", "Полина")) == "Коля"
    sample = "[10:00] Я: Ань, ты скинешь пример?\n[10:01] Собеседник: Угу."
    assert trustworthy_name("Ань", sample=sample, label="Собеседник",
                            owner_name=OWNER, known=("Аня",)) == "Аня"


def test_vocative_is_exact_and_narrow():
    """Формы выводятся детерминированно; склейка — только при точном совпадении.

    «Мариш» при известной «Марине» не склеивается (Мариша ≠ Марина); имя на
    гласную — уже именительный; «Влад» + «а» — другой человек (стоп-лист);
    длинное «Александр» и «Голенков» на фамилию не трогаем; «Игорь» даёт
    форму «Игоря», которой среди людей не бывает, — значит, останется Игорем."""
    from speaker_names import nominative_candidates, resolve_vocative
    assert nominative_candidates("Коль") == ("Коля", "Колья")
    assert nominative_candidates("Иль") == ("Иля", "Илья")
    assert nominative_candidates("Саш") == ("Саша",)
    assert nominative_candidates("Зой") == ("Зоя",)
    for nominative in ("Коля", "Аня", "Марина", "Ан", "Влад", "Александр", "Голенков",
                       "Ильин", "Полин", "Николай"):
        assert nominative_candidates(nominative) == (), nominative
    assert resolve_vocative("Мариш", ("Марина",)) is None
    assert resolve_vocative("Игорь", ("Игорь", "Игоря")) == "Игоря"  # только если такой человек есть
    assert resolve_vocative("Коль", ("Коля", "Коля Иванов")) == "Коля"
    assert resolve_vocative("Иль", ("Илья",)) == "Илья"
    assert resolve_vocative("Иль", ("Илья", "Иля")) is None   # две формы — не гадаем
    assert resolve_vocative("Тань", ()) is None


def test_prefix_fold_and_stop_list_hold_in_the_full_path():
    """«Андрюх» → «Андрей» по префиксу как раньше; «Иль» при Илье и Иле решает префикс;
    «Влад» не становится «Владой» ни звательным ходом, ни префиксным (DS I1, круг 1 #508)."""
    sample = "[10:00] Я: Андрюх, глянь.\n[10:01] Собеседник: Смотрю."
    assert trustworthy_name("Андрюх", sample=sample, label="Собеседник",
                            owner_name=OWNER, known=("Андрей",)) == "Андрей"
    sample = "[10:00] Я: Иль, ты здесь?\n[10:01] Собеседник: Да."
    assert trustworthy_name("Иль", sample=sample, label="Собеседник",
                            owner_name=OWNER, known=("Илья", "Иля")) == "Илья"
    sample = "[10:00] Я: Влад, привет.\n[10:01] Собеседник: Привет."
    assert trustworthy_name("Влад", sample=sample, label="Собеседник",
                            owner_name=OWNER, known=("Влада",)) == "Влад"


