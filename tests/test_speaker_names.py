def test_метка_канала_владельца_закрывает_гейт_мгновенных_ответов():
    """Пока реплики владельца шли как «Собеседник N», гейт считал их чужими
    и ⚡ отвечала на вопросы самого хозяина встречи (ревью 19.08, DeepSeek).
    Подпись по каналу это закрывает — здесь проверяется обе формы метки:
    имя из настроек и «Я», когда имя не задано."""
    assert not is_counterpart("Игорь Ветров", "Игорь Ветров")
    assert is_counterpart("Собеседник 2", "Игорь Ветров"), \
        "а вот нейтральная метка по-прежнему считается той стороной"
    # Имя не задано: демон сверяет с меткой своего канала, иначе гейт
    # остаётся открытым на собственные вопросы (ревью 19.08).
    assert not is_counterpart("Я", "Я")
    assert is_counterpart("Я", ""), \
        "без опоры отсечь владельца нечем — демон и передаёт ему «Я»"


def test_метка_своего_канала_закрывает_гейт_любым_именем():
    """Гейт мгновенных ответов не должен зависеть от того, как названа
    метка: своя дорожка — это владелец по определению, а не догадка об
    имени. Сверка только по user_name ломалась дважды: при незаданном имени
    метка «Я» считалась чужой, а при имени, совпавшем с нейтральной меткой,
    захват подставлял «Я», и ⚡ снова отвечала на вопросы хозяина встречи
    (ревью 19.08, круги 4 и 7). Здесь закреплена сама сверка по имени;
    сверку по метке канала демон делает до неё."""
    assert not is_counterpart("Я", "Я")
    assert not is_counterpart("Игорь Ветров", "Игорь Ветров")
    assert is_counterpart("Собеседник 2", "Игорь Ветров")


def test_коллизионное_имя_не_делает_владельцем_всех_собеседников():
    """`is_owner` сравнивает по четырёхбуквенному префиксу, и имя
    «Собеседник 2» в настройках делает владельцем КАЖДОГО «Собеседник N».
    В гейте мгновенных ответов это глушило ⚡ для всех собеседников разом
    на всю встречу (ревью 19.08, девятый круг). Демон такое имя в сверку
    по имени не пускает; здесь закреплено само свойство `is_owner`, из-за
    которого пускать нельзя."""
    assert is_owner("Собеседник 1", "Собеседник 2"), \
        "префиксное правило срабатывает — поэтому демон и обходит его"
    assert is_owner("Собеседник 3", "Собеседник")
    assert not is_owner("Мария", "Собеседник 2")


