import pytest

# `src/` в пути: фикстуры conftest трогают канон путей раньше, чем первый
# тест успеет вставить его себе сам.
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "src"))

import charoite_paths  # noqa: E402


def нарушение_маркера(корни) -> str:
    """Предусловие маркера `настоящий_корень_ревизии` одной функцией.

    Свойство, а не место: корень процесса обязан быть ВРЕМЕННЫМ. База
    прогона pytest слишком узка — `tempfile.mkdtemp()` уже принятая в проекте
    идиома (`test_channel_trace.py`, `test_audio_capture.py`), и её каталог
    лежит рядом с базой, а не внутри (круг 9 по коду №327, DS I2). Установка,
    `$HOME` и живой корень данных владельца остаются вне `gettempdir()` —
    именно они и опасны: ревизия писала бы туда снимки, карантин и отметки
    brain по настоящим встречам.

    Судим ВСЕ корни, названные за тест, а не финальное состояние: тест,
    сходивший на корень установки и вернувшийся в tmp, иначе прошёл бы
    незамеченным. Пустая строка — нарушения нет.
    """
    tmp = pathlib.Path(tempfile.gettempdir()).resolve()
    if not корни:
        return ("тест с маркером настоящий_корень_ревизии не назвал корень "
                "данных: ревизия писала бы в корень установки")
    # `resolve()` с обеих сторон: `mkdtemp()` отдаёт `/var/folders/…`, а
    # `gettempdir()` после резолва — `/private/var/folders/…` (симлинк macOS),
    # и сравнение сырых строк объявляло бы законный временный корень чужим.
    плохие = [к for к in корни if not к.resolve().is_relative_to(tmp)]
    if плохие:
        return (f"тест с маркером настоящий_корень_ревизии работал на корне "
                f"{плохие[0]} — он не временный, и ревизия писала бы снимки туда")
    return ""


