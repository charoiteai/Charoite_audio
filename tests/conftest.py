def не_временный_корень(корни, *, обязан_назвать: bool = True) -> str:
    """Корень данных обязан быть временным — одной функцией на весь прогон.

    Свойство, а не место: корень процесса обязан быть ВРЕМЕННЫМ. База
    прогона pytest слишком узка — `tempfile.mkdtemp()` уже принятая в проекте
    идиома (`test_channel_trace.py`, `test_audio_capture.py`), и её каталог
    лежит рядом с базой, а не внутри (круг 9 по коду №327, DS I2). Установка,
    `$HOME` и живой корень данных владельца остаются вне `gettempdir()` —
    именно они и опасны: ревизия писала бы туда снимки, карантин и отметки
    brain по настоящим встречам.

    Судим ВСЕ корни, названные за тест, а не финальное состояние: тест,
    сходивший на корень установки и вернувшийся в tmp, иначе прошёл бы
    незамеченным. Пустая строка — нарушения нет.
    """
    tmp = pathlib.Path(tempfile.gettempdir()).resolve()
    if not корни and обязан_назвать:
        return ("корень данных не назван — канон ответил бы положением файла, "
                "то есть корнем кода: в рабочем checkout это живые данные владельца")
    # `resolve()` с обеих сторон: `mkdtemp()` отдаёт `/var/folders/…`, а
    # `gettempdir()` после резолва — `/private/var/folders/…` (симлинк macOS),
    # и сравнение сырых строк объявляло бы законный временный корень чужим.
    плохие = [к for к in корни if not к.resolve().is_relative_to(tmp)]
    if плохие:
        return (f"корень {плохие[0]} не временный — продуктовый код писал бы туда "
                "снимки, карантин, логи и отметки brain по настоящим встречам")
    return ""


#: Маркер теста, который называет корень данных сам: канон корней — его
#: предмет (`test_charoite_paths.py`) или ему нужен корень особой формы.
#: Обвязка такому тесту корень не называет: второй корень канон отвергает, и
#: это его работа, а не помеха.
МАРКЕР_СВОЙ_КОРЕНЬ = "корень_называет_тест"

#: Маркер «окружение как в жизни» для облачной ревизии — тоже про корень:
#: помеченный тест называет его сам, и обвязка ему не мешает.
МАРКЕР_КОРЕНЬ_РЕВИЗИИ = "настоящий_корень_ревизии"


def корень_называет_тест(node) -> bool:
    """Оба маркера значат одно: корень данных в этом тесте — предмет, не фон."""
    return any(node.get_closest_marker(имя) is not None
               for имя in (МАРКЕР_СВОЙ_КОРЕНЬ, МАРКЕР_КОРЕНЬ_РЕВИЗИИ))


