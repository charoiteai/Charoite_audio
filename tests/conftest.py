            charoite_paths.use_data_root = дверь
            # Тест канона вправе не назвать корень вовсе: он проверяет отказ
            # («пустой корень», «чужая переменная сильнее»). Требование
            # «назови хоть что-то» осталось за маркером ревизии — там
            # безымянный корень означает запись снимков в корень установки.
            обязан = request.node.get_closest_marker(МАРКЕР_КОРЕНЬ_РЕВИЗИИ) is not None
            из_окружения = os.environ.get("CHAROITE_ROOT")
