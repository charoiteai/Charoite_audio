/// Какие модели предложить на ЭТОЙ машине.
///
/// До этого пресеты жили комментарием в config.example.yaml («16GB RAM:
/// model: gemma4:latest») и таблицей в MODELS.md. Человек должен был сам
/// узнать объём своей памяти, найти нужную строчку и перенести значения в
/// конфиг — три шага, на каждом из которых можно ошибиться молча: слишком
/// тяжёлая модель не падает, она просто уходит в своп, и подсказка на
/// встрече приходит через минуту вместо секунды.
///
/// Теперь приложение смотрит на память само и показывает готовые варианты.
struct ModelPreset: Identifiable, Equatable {
    /// Ключ пресета — он же id для SwiftUI.
    let id: String
    /// Название для человека: «Полный», «Сбалансированный», «Лёгкий».
    let title: String
    /// Основная модель — подсказки, саммари, имена.
    let model: String
    /// Лёгкая — тезисы и классификация, работает фоном всю встречу.
    let smallModel: String
    /// С какого объёма памяти этот набор рекомендуется, ГБ.
    ///
    /// Это порог выбора, а не вес связки: «Полный» просит 24 ГБ моделями
    /// (20.4 + 3.2) и формально влезает в 48, но рекомендуется с 64 —
    /// с запасом на STT, эмбеддер, систему и браузер.
    let needsGB: Int
    /// Собирать ли граф знаний после встречи.
    ///
    /// Не косметика описания, а строка в конфиге (`sufler.graph`). Все
    /// профили держат его включённым: бенч 19.08 показал, что разбор в узлы
    /// тянет даже 4B (31 решение, 96% проверяемых цитат), — правило «ниже
    /// 16 ГБ графа нет» отменено. Флаг остаётся ручным выключателем для
    /// того, кому граф не нужен вовсе.
    let graph: Bool
    /// Семантическое «⏮ уже обсуждалось» (`sufler.deja_vu`): держит рядом
    /// эмбеддер bge-m3, ещё 1.2 ГБ резидентно.
    let dejaVu: Bool
    /// Ревизия ядер после встречи (`sufler.tier3`) — тот же bge-m3, поэтому
    /// выключается вместе с дежавю: иначе обещание «эмбеддер здесь не живёт»
    /// ломается на первой же встрече (ревью 19.08).
    var tier3: Bool { dejaVu }
    /// Модель тезисов и черновика минуток (`sufler.think_model`). Идёт каждые
    /// 40–150 секунд всю встречу, поэтому на лёгких машинах это лёгкая
    /// модель, а не «та же, что основная».
    var thinkModel: String { needsGB >= 64 ? model : smallModel }
    /// Модель разметки реплик (`sufler.markup_model`) — см. configFlags.
    var markupModel: String { needsGB >= 32 ? model : smallModel }
    /// Чем этот вариант отличается — одной фразой.
    let note: String

    /// Модели, которые нужно скачать для этого пресета.
    ///
    /// Без дубля: в лёгком наборе обе роли обслуживает одна модель, и
    /// качать её дважды — значит показать человеку две одинаковые строки
    /// прогресса и один и тот же гигабайт в счёте.
    var models: [String] { model == smallModel ? [model] : [model, smallModel] }

    /// Одна модель на обе роли — так устроен набор для 8 ГБ.
    var isSingleModel: Bool { model == smallModel }

    /// Что этот профиль пишет в config.yaml помимо моделей.
    ///
    /// Значения строками: их кладёт AppSettings.setConfigValue, а Python
    /// читает через install_profile.flag — он понимает и `false`, и "false".
    var configFlags: [(key: String, value: String)] {
        [("graph", graph ? "true" : "false"),
         ("deja_vu", dejaVu ? "true" : "false"),
         ("tier3", tier3 ? "true" : "false"),
         ("think_model", thinkModel),
         // Разметка реплик требует ДОСЛОВНОСТИ: валидация сверяет слова и
         // режет любой ответ, где модель хоть что-то поправила (бенч 21.07 —
         // 4B правит, gemma держит). В примере конфига стоял gemma4:latest,
         // которого не качает ни один профиль, — контур молча отсутствовал у
         // всех. Пишем модель, которая на этой машине и так резидентна: на
         // тяжёлых профилях основную, на лёгких — ту же лёгкую, и в доках
         // честно сказано, что там разметка срабатывает реже.
         ("markup_model", markupModel)]
    }
}

enum ModelPresetPolicy {

    /// Все варианты, от тяжёлого к лёгкому.
    ///
    /// Цифры памяти — из манифестов Ollama (19.08), а не на глаз:
    /// qwen3.6:35b-mlx 20.4 ГБ, qwen3.8:27b-mlx 16.9, gemma4:12b 7.0,
    /// gemma4:latest (он же e4b) 8.9, qwen3.5:4b 3.2, qwen3.5:2b 2.6.
    /// К связке добавлен запас на систему, STT (~1 ГБ), диаризацию (~0.5) и
    /// браузер: модель, занявшая всю память, тормозит именно ту встречу, ради
    /// которой её и ставили.
    ///
    /// Составы — из бенча 19.08 на разборе трёх реальных встреч
    /// (scripts/bench_extract.py, та же методика, что 14.08):
    ///
    ///   35b-mlx  3/3, 42 решения, 39 ядер, цитаты 92%, медиана 57 с
    ///   27b-mlx  3/3, 47 решений, 31 ядро, цитаты 96%, медиана 224 с
    ///   12b      3/3, 28 решений, 24 ядра, цитаты 100%, медиана 353 с
    ///   4b       3/3, 31 решение, 30 ядер, цитаты 96%, медиана 113 с
    ///   e4b      3/3, 16 решений, 23 ядра, цитаты 95%, медиана 152 с
    ///   GigaChat 2/3 — сломанный JSON на пяти частях из шести, исключена
    ///
    /// Отсюда две правки против прежней таблицы: gemma4:latest (8.9 ГБ)
    /// уступает gemma4:12b (7.0 ГБ) и по весу, и по находкам, а 4B на 8 ГБ
    /// разбирает граф лучше, чем 12B, — правило «меньше 30B ломают JSON»
    /// держалось на GigaChat-подобных моделях, а не на классе размера.
    static let all: [ModelPreset] = [
        ModelPreset(
            id: "full",
            title: L.t("Полный", "Full", "完整"),
            model: "qwen3.6:35b-mlx",
            smallModel: "qwen3.5:4b",
            needsGB: 64,
            graph: true, dejaVu: true,
            note: L.t("Наш рабочий набор: 42 решения и 39 ядер на встречу, медиана разбора 57 с.",
                      "Our working set: 42 decisions and 39 cores per meeting, 57 s median.",
                      "我们的日常配置：每场会议 42 条决定、39 个核心，解析中位数 57 秒。")),
        ModelPreset(
            id: "precise",
            title: L.t("Точный", "Precise", "精确"),
            model: "qwen3.8:27b-mlx",
            smallModel: "qwen3.5:4b",
            needsGB: 32,
            graph: true, dejaVu: true,
            note: L.t("Точнее по цитатам (96%). Разбор втрое дольше, но он фоновый, а подсказки и нить идут на лёгкой модели.",
                      "More accurate quotes (96%). Extraction is three times slower, but it runs in the background, while hints and the thread use the light model.",
                      "引用更准确（96%）。解析慢三倍，但它在后台运行，提示与脉络使用轻量模型。")),
        ModelPreset(
            id: "balanced",
            title: L.t("Сбалансированный", "Balanced", "均衡"),
            // Та же 4B, что на 8 ГБ, — и это не экономия ради экономии:
            // в бенче 19.08 она дала БОЛЬШЕ находок, чем gemma4:12b
            // (31 решение против 28, 30 ядер против 24), и втрое быстрее.
            // Единственный выигрыш 12B — 100% цитат против 96%, а цена —
            // 3.8 лишних гигабайта: с эмбеддером, STT и системой связка
            // 12b+4b упиралась в 17–19 ГБ на 16-гигабайтной машине, то есть
            // в тот самый своп, от которого профили и защищают (ревью 19.08).
            model: "qwen3.5:4b",
            smallModel: "qwen3.5:4b",
            needsGB: 16,
            graph: true, dejaVu: true,
            note: L.t("Та же модель, что на 8 ГБ, плюс семантическая память: дежавю и ревизия ядер.",
                      "The same model as on 8 GB plus semantic memory: déjà vu and core revision.",
                      "与 8 GB 相同的模型，另加语义记忆：既视感与核心复核。")),
        // 8 ГБ — одна модель на обе роли. Граф здесь ВКЛЮЧЁН: бенч 19.08
        // (scripts/bench_extract.py, три встречи 24–106 тыс. знаков) снял
        // старое правило «меньше 30B ломают JSON»: qwen3.5:4b разобрала 3/3,
        // 31 решение, 30 ядер, 96% цитат — больше находок, чем у gemma4:12b,
        // и втрое быстрее. Выключено другое — дежавю: bge-m3 держал бы рядом
        // с системой ещё 1.2 ГБ, а без него живой контур помещается.
        ModelPreset(
            id: "light",
            title: L.t("Лёгкий", "Light", "轻量"),
            model: "qwen3.5:4b",
            smallModel: "qwen3.5:4b",
            needsGB: 8,
            graph: true, dejaVu: false,
            note: L.t("Впритык: одна модель на обе роли, граф работает, семантическая память выключена.",
                      "Tight fit: one model for both roles, the graph works, semantic memory is off.",
                      "空间紧张：一个模型兼顾两种角色，图谱可用，语义记忆关闭。")),
    ]

    /// Память машины в гигабайтах.
    static var machineMemoryGB: Int {
        Int(ProcessInfo.processInfo.physicalMemory / 1_073_741_824)
    }

    /// Что рекомендовать при таком объёме памяти.
    ///
    /// Правило намеренно консервативное: берём пресет, который помещается с
    /// запасом. На 16 ГБ формально влезает и «Полный» — но вместе с системой,
    /// браузером и созвоном он уйдёт в своп, и человек решит, что продукт
    /// медленный, а не что модель не по машине.
    static func recommended(forGB memory: Int) -> ModelPreset {
        if memory >= 64 { return all[0] }   // «Полный»: 35B просит ~21 ГБ весов
        if memory >= 32 { return all[1] }   // «Точный»: 27B, ~17 ГБ
        if memory >= 16 { return all[2] }   // «Сбалансированный»: 12B, ~7 ГБ
        return all[3]                        // «Лёгкий»: одна 4B на обе роли
    }

    /// Значение флага из конфига: выключено или нет.
    ///
    /// Зеркало `install_profile.flag` на стороне Python — конфиг человек
    /// правит руками и пишет туда «нет» или «off» так же охотно, как false.
    /// Живёт здесь, а не во вью: в Views русские литералы мимо `L.t`
    /// запрещены (LocalizationTests), а это не текст интерфейса.
    static func flagIsOn(_ value: String?) -> Bool? {
        guard let value = value?.trimmingCharacters(in: .whitespaces).lowercased(),
              !value.isEmpty else { return nil }
        let off = ["false", "no", "off", "0", "\u{043D}\u{0435}\u{0442}"]   // «нет»
        return !off.contains(value)
    }

    /// Пресет по ключу — для восстановления выбора из конфига.
    static func preset(id: String) -> ModelPreset? {
        all.first { $0.id == id }
    }

    /// Какой пресет сейчас записан в конфиге.
    ///
    /// Сверяем обе модели: человек мог поправить одну строку руками, и
    /// показывать ему «Полный» с лёгкой моделью было бы неправдой.
    ///
    /// И флаги семантической памяти: у «Сбалансированного» и «Лёгкого» одна
    /// и та же 4B (бенч 19.08), различает их только `deja_vu`. Без этого на
    /// 8-гигабайтной машине мастер показывал бы «Сбалансированный», а
    /// сохранение молча включало бы дежавю и ревизию ядер — то есть bge-m3
    /// и своп (ревью 19.08, второй круг Gemini).
    static func current(model: String?, smallModel: String?,
                        dejaVu: Bool? = nil) -> ModelPreset? {
        guard let model, let smallModel else { return nil }
        return all.first {
            $0.model == model && $0.smallModel == smallModel
                && (dejaVu == nil || $0.dejaVu == dejaVu)
        }
    }
}

#endif
