#!/bin/bash
# Ночной «сон» Чароита (launchd ru.charoit.tier3, 04:15):
#   1) Утренний бриф _Сегодня.md — сразу, до тяжёлых шагов
#   2) Tier3-ревизия ядер всех графов (дубли/вложения/пометки, с бэкапами)
#   3) Досье по темам, облачные ревизии, дедуп файлов
#   4) Бриф ещё раз — уже поверх причёсанных ядер и свежих досье
#
# Почему бриф дважды. Раньше он стоял последним и читал уже причёсанный граф —
# логично ровно до тех пор, пока ревизия укладывалась в ночь. На графе в три
# сотни ядер полный прогон идёт часами, и 13.08 бриф не был написан к девяти
# утра вовсе: человек читал вчерашний файл. Бриф стоит секунды и модель не
# зовёт, поэтому дешевле написать его дважды, чем один раз, но к обеду.
#
# Коды возврата. Шаги независимы: упавшая ревизия не отменяет бриф, поэтому
# каждый шаг ловится отдельно и только помечает прогон неуспешным. Без этого
# джоба всегда заканчивалась echo, то есть exit 0, и launchd показывал зелёный
# прогон даже когда ночью не делалось вообще ничего.
set -euo pipefail
cd "$(dirname "$0")/.." || exit 1
PY=.venv/bin/python
# Ночью держим в памяти одну модель вместо трёх по кругу: см. комментарий в
# src/llm.py. Днём переменная не выставлена, и мелкие задачи по-прежнему
# уходят на маленькую модель.
export CHAROITE_ONE_MODEL=1
# Python буферизует stdout в файл, и лог ночи появлялся одним куском в конце:
# отличить «идёт третий час» от «висит намертво» было нельзя ничем, кроме ps.
export PYTHONUNBUFFERED=1
# Ночная работа обязана кончаться ночью. 21.08 прогон стартовал в 04:16 и в
# 11:36 всё ещё держал машину: занятость спрашивали ОДИН раз, на старте, когда
# всё свободно, а дальше семь часов никто не смотрел на часы — живая встреча
# 11:03 шла поверх ночного цикла, и стенограмма рвалась. Потолок видят и шаги
# (через live_gate.night_is_over), поэтому длинный шаг прервётся между темами,
# а не только на границе шагов. Несделанное соберётся следующей ночью.
# Мусор в NIGHTLY_MAX_H (например «4h») валил арифметику, а set -e выносил
# скрипт ДО раннего брифа — вопреки правилу «бриф и статус идут всегда»
# (круг по PR #363, GLM). Не число — молча берём дефолт.
NIGHTLY_MAX_H=${NIGHTLY_MAX_H:-4}
case "$NIGHTLY_MAX_H" in (""|*[!0-9]*) NIGHTLY_MAX_H=4;; esac
# 08/09 — все цифры, но bash счёл бы их восьмеричными и упал; 10# — десятичное
NIGHTLY_MAX_H=$((10#$NIGHTLY_MAX_H))
export CHAROITE_NIGHTLY_UNTIL=$(( $(date +%s) + NIGHTLY_MAX_H * 3600 ))
# Один прогон ночи на машину. launchd свою джобу не задваивает, но ручной
# запуск поверх идущего давал два процесса, которые перезаписывают друг другу
# статус и отметки tier3, сталкиваются одинаковым «Тема.md.tmp» и теряют
# строки хроники при параллельном слиянии (аудит ночи 26.08, GLM Important 4).
# Лок каталогом, а не flock: flock на macOS без util-linux нет, а python здесь
# звать нельзя — им же подменяют шаги в тестах. mkdir атомарен на любой ФС;
# протухший лок узнаём по мёртвому pid.
LOCKDIR="${CHAROITE_ROOT:-$PWD}/logs/nightly.lock.d"
mkdir -p "$(dirname "$LOCKDIR")"
if ! mkdir "$LOCKDIR" 2>/dev/null; then
  OTHER=$(cat "$LOCKDIR/pid" 2>/dev/null || echo "")
  if [ -n "$OTHER" ] && kill -0 "$OTHER" 2>/dev/null; then
    echo "ночной прогон уже идёт (pid $OTHER) — выхожу"
    exit 0
  fi
  echo "⚠️ остался лок мёртвого прогона (pid ${OTHER:-неизвестен}) — забираю"
  rm -rf "$LOCKDIR" && mkdir "$LOCKDIR" 2>/dev/null || true
fi
echo $$ > "$LOCKDIR/pid" 2>/dev/null || true
cleanup_lock() { rm -rf "$LOCKDIR"; }

rc=0
STARTED=$(date '+%F %T')
# Куда кладём машиночитаемый итог. Логи launchd живут в /tmp и исчезают при
# перезагрузке — по ним нельзя отличить «ночью ничего не делалось» от
# «файл стёрся». Статус нужен рядом с данными и должен переживать ребут:
# его читает приложение и показывает на «Сегодня».
STATUS_DIR="${CHAROITE_ROOT:-$PWD}/logs"
STATUS="$STATUS_DIR/nightly.json"
FAILED=""
STATUS_DONE=0
mkdir -p "$STATUS_DIR"

# Пишем статус в любом случае — в том числе если прогон оборвут на середине:
# незавершённый прогон это тоже факт, и человек должен его увидеть.
write_status() {
  local state="$1"
  # «идёт» — не итог: после него статус ещё обязан быть переписан.
  [ "$state" = running ] || STATUS_DONE=1
  printf '{"started":"%s","finished":"%s","state":"%s","rc":%s,"failed":"%s"}\n' \
    "$STARTED" "$(date '+%F %T')" "$state" "$rc" "$FAILED" > "$STATUS"
}
# Заголовок шага со временем: по нему видно, сколько съел предыдущий, — без
# этого «долго» и «встало» в логе выглядят одинаково.
step() {
  echo "--- $1 ($(date '+%T')) ---"
  # Сердцебиение статуса: night_running (busy_signals) судит о живости
  # ночи по mtime nightly.json; без обновления на границах шагов ночь
  # длиннее NIGHT_STALE_S становилась невидимой мутатору (круг-2 по
  # PR #399, DS Important) — статус переписываем на каждом шаге.
  [ "$STATUS_DONE" = 1 ] || write_status running
}
# Тяжёлый шаг не начинаем, если время ночи уже вышло: шаги видят потолок и
# сами, но начинать заведомо лишний час работы незачем. Бриф и статус идут
# всегда — они секундные и нужны человеку к утру.
overdue() { [ "$(date +%s)" -gt "$CHAROITE_NIGHTLY_UNTIL" ]; }
skip_late() { echo "⏭️ $1 пропущен: время ночного прогона вышло"; FAILED="$FAILED $2"; }
# exit ОБЯЗАТЕЛЕН: без него bash выполняет ловушку и идёт дальше, а финальный
# write_status затирает «interrupted» на «ok» — прогон продолжал держать
# машину после явного требования остановиться, и состояние «прервана» было
# недостижимо через сигнал вовсе (аудит ночи 26.08, GLM Critical 1).
trap 'write_status interrupted; cleanup_lock; exit 143' INT TERM
# set -e выносит скрипт из любой необработанной команды, и статус остался бы
# «идёт» навсегда — поломка, замаскированная под работу.
trap '[ "$STATUS_DONE" = 1 ] || { rc=1; write_status failed; }; cleanup_lock' EXIT

# Пишем «идёт» сразу: прогон занимает от четверти часа до часа с лишним
# (ревизия ядер и досье — это локальная модель на каждой теме), и всё это
# время на экране не должно висеть «не запускалось».
write_status running

echo "=== nightly $(date '+%F %T') ==="
# «Не отвалилось ничего» и «работы не было» — разные ночи. Без графа
# (отключённый диск, несмонтированный iCloud) каждый шаг честно выходит
# нулём, и статус зеленел при нуле сделанного (аудит ночи 26.08, GLM
# Important 5).
if ! $PY -c "import sys; sys.path.insert(0, 'src'); import graphs; sys.exit(0 if graphs.all_graphs('Ядра') else 1)" 2>/dev/null; then
  echo "⚠️ графов с папкой «Ядра» не видно — ночь пройдёт вхолостую"
  FAILED="$FAILED графов-нет"
fi
# Разбор вечерней встречи вполне может идти и в 04:15. Вместе с ночным
# циклом они делят одну память и одну локальную модель — и оба буксуют.
# Ждём с потолком: пропустить ночь целиком хуже, чем поработать в тесноте.
# --root — корень ДАННЫХ: лок живого демона и статусы разбора лежат там,
# а не рядом с кодом (вложенная установка; ревью 18.08)
$PY scripts/wait_for_idle.py --root "${CHAROITE_ROOT:-$PWD}" --timeout "${NIGHTLY_WAIT:-3600}" || true

step "morning brief (ранний)"
# Страховочный проход: бриф на данных, какие есть. Упал — не авария, впереди
# основной; ронять из-за него ночь нельзя.
$PY scripts/morning_brief.py || echo "⚠️ ранний бриф не отработал — ждём основной"

step "tier3 cores"
# право на слияние — у конфига (sufler.tier3_auto_apply), не у cron:
# --auto сливает только при true, иначе обратимые пометки (--mark)
#
# Полный прогон квадратичен: 293 ядра — сорок тысяч пар, каждую кандидатскую
# судит NLI в один поток, и ночь кончается раньше ревизии. По будням судим
# только ядра, изменившиеся с прошлого прогона (их единицы), раз в неделю —
# всё против всего, потому что пороги и модель со временем меняются и полная
# сверка ловит то, что инкремент структурно увидеть не может.
TIER3_MODE=--since-last
if [ "$(date +%u)" = "7" ] || [ "${NIGHTLY_TIER3_FULL:-0}" = "1" ]; then
  TIER3_MODE=""
  echo "полная ревизия (воскресенье или NIGHTLY_TIER3_FULL=1)"
fi
# Самый долгий шаг ночи обязан слушаться потолка так же, как остальные:
# воскресный полный прогон квадратичен и шёл бы часами (круг по PR #363,
# GLM + DeepSeek — «инвариант ночи не выполняется для шага, который дольше
# всех»). Вторая граница — внутри tier3_cores, между графами.
if overdue; then
  skip_late "ревизия ядер" "tier3(поздно)"
else
  $PY scripts/tier3_cores.py --all-graphs --auto $TIER3_MODE || {
    case $? in
      # 2 — «прошло вхолостую»: нет NLI-модели или лежит Ollama. Ночь с таким
      # шагом не «ok», но и не авария (аудит ночи 26.08, DS Important 4).
      2) echo "⚠️ ревизия ядер не состоялась — модель не отвечала"
         FAILED="$FAILED ревизия-ядер(вхолостую)" ;;
      *) echo "❌ РЕВИЗИЯ ЯДЕР УПАЛА (код $?)"; rc=1; FAILED="$FAILED ревизия-ядер" ;;
    esac
  }
fi
step "dossiers"
# Сводки по темам поверх ядер + индекс для поиска. Инкрементально:
# пересобираются только темы, у которых изменился хоть один источник.
# Код 2 — особый: скрипт отработал, но модель массово не отвечала, и темы
# остались без разбора. Снаружи это выглядит как успешная ночь, поэтому
# различаем: «шаг упал» и «шаг прошёл вхолостую» — разные беды, и вторая
# опаснее, её не видно.
$PY scripts/nightly_dossier.py --all-graphs || {
  case $? in
    2) echo "⚠️ досье собирались без модели — темы остались без разбора"
       FAILED="$FAILED досье(модель-молчала)" ;;
    *) echo "⚠️ сборка досье не отработала"; FAILED="$FAILED досье" ;;
  esac
}
step "dossier review (cloud, optional)"
# Второй проход по свежим досье: облако видит связи между источниками,
# которых локальная модель не замечает. Правит сам только при
# sufler.cloud_edit_graph: true, иначе пишет отчёт-рекомендации.
if overdue; then
  skip_late "ревизия досье" "ревизия-досье(поздно)"
else
  $PY scripts/nightly_dossier_review.py --all-graphs || echo "⚠️ ревизия досье не отработала"
fi
step "claude cores review"
# облачный взгляд на ядра (Opus): отчёт-рекомендации, ничего не правит.
# Выключено sufler.cloud_enrich/SUFLER_NO_CLOUD — шаг молчит.
# Код 2 — «ответ облака не принят» (отказ, лимит, нет секций): раньше любой
# ненулевой код гасился эхом, и ночь писала «ok» без файла ревизии, а бриф
# молча терял разделы (аудит 17.08). rc не трогаем: шаг необязательный.
if overdue; then
  skip_late "облачная ревизия ядер" "claude-cores(поздно)"
else
  $PY scripts/nightly_claude_cores.py || {
    case $? in
      2) echo "⚠️ облачная ревизия ядер не принята"; FAILED="$FAILED claude-cores(не-принята)" ;;
      *) echo "⚠️ облачная ревизия не отработала"; FAILED="$FAILED claude-cores" ;;
    esac
  }
fi
step "dedup graph files"
# Побайтовые копии документов встречи (оригинал в «Документация», копия в
# «Встречи-архив» для Finder) связываются жёсткими ссылками: место и
# синхронизация iCloud перестают удваиваться, оба пути остаются рабочими.
# Не путать с ревизией ядер выше — та сшивает СМЫСЛОВЫЕ дубли тем.
if overdue; then
  skip_late "дедупликация файлов" "дедуп(поздно)"
else
  $PY scripts/dedup_graph.py || { echo "⚠️ дедупликация файлов не отработала"; FAILED="$FAILED дедуп"; }
fi

step "morning brief"
$PY scripts/morning_brief.py || { echo "❌ УТРЕННИЙ БРИФ УПАЛ (код $?)"; rc=1; FAILED="$FAILED утренний-бриф"; }
step "memory bench"
# не валит джобу: exit 1 бенча = сигнал деградации в логе, не авария
# Бенч зовёт локальную модель — под потолок его, как и прочие тяжёлые шаги
# (аудит ночи 26.08, DS Important 1: гейта не было, и после потолка бенч
# всё равно поднимал модель).
if overdue; then
  skip_late "бенч памяти" "бенч(поздно)"
else
  $PY scripts/memory_bench.py || echo "⚠️ БЕНЧ ПАМЯТИ ПРОСЕЛ — смотри выше"
fi
echo "=== done $(date '+%F %T'), rc=$rc ==="
FAILED="${FAILED# }"
# «ok» — только когда не отвалилось НИЧЕГО. Код возврата мягче: им мы
# сообщаем launchd об авариях, а человеку на экране важно и то, что дедуп
# файлов не отработал или досье собрались без модели, — при rc=0 такая ночь
# выглядела бы полностью успешной.
if [ "$rc" -eq 0 ] && [ -z "$FAILED" ]; then write_status ok; else write_status failed; fi
exit $rc
