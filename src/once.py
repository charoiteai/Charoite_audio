"""Одна память «уже сказали» на процесс вместо шести копий в модулях.

Отказы и подсказки, которые повторяются на каждом вызове, — не новость, а
шум: сервер без грамматики отвечает так на каждый запрос, http-отказ
повторяется с той же парой «код + тело», копия импорта живёт по одному сроку
весь день. В журнале встречи повторение одной строки вытесняет настоящую
причину, поэтому каждый такой модуль держал свой набор `_said` и печатал
строку один раз. Здесь этот набор один: реестр на процесс, общий для всех.

Ключ — пара `(пространство, смысл)`. Пространство — кто говорит (`embed`,
`config`, `llm`), оно же имя для `reset`. В смысл входит то, что делает
повтор ПОВТОРОМ: код ответа, тело, форма, вид исключения, путь, — а не
готовая строка целиком. Строка с той же причиной, но другими цифрами в
подробностях, тогда звучит снова (это новое событие), а та же беда,
пересказанная другими словами, — нет.

Слой base: только stdlib, ничего из репозитория.
"""
from __future__ import annotations

import sys
import threading

#: Ключ: `(пространство, смысл)`. Смысл — хешируемое описание повтора, не
#: обязательно строка (`mlx` кладёт пару моделей кортежем).
Key = tuple[str, object]

_lock = threading.Lock()
_said: set[Key] = set()


def first(key: Key) -> bool:
    """True — этого ключа ещё не было (и запоминает его); False — уже сказали.

    Решение и пометка — под одним замком модуля: два потока на одном ключе
    получают True ровно один раз, и строка не двоится.
    """
    with _lock:
        if key in _said:
            return False
        _said.add(key)
        return True


def say(key: Key, text: str) -> bool:
    """Первая на ключ строка `text` в stderr; True — напечатали.

    Замок берётся только на решение «первый ли это раз»: печать идёт после
    выхода из него, поэтому медленный поток к одной беде не держит `forget`
    чужой. Печать обёрнута в `try/except Exception` — строка о неполадке не
    роняет работу, ради которой заведена. Напечатать не удалось — ключ
    забывается (`forget`): следующая попытка скажет снова, и молчание не
    останется навсегда.
    """
    if not first(key):
        return False
    try:
        print(text, file=sys.stderr, flush=True)
    except Exception:      # noqa: BLE001 — строка о неполадке не роняет работу
        forget(key)
        return False
    return True


def forget(key: Key) -> None:
    """Эпизод кончился: ключ можно сказать снова.

    Зовётся, когда причина ушла и вернулась (сервер принял строгий JSON, а
    потом снова его потерял), — новый эпизод владелец должен увидеть.
    """
    with _lock:
        _said.discard(key)


def reset(namespace: str | None = None) -> None:
    """Забыть всё (`None`) или только ключи одного пространства.

    Нужно там, где состояние модуля сбрасывают целиком (реестр строгого JSON
    на перезапуске или в тестах).
    """
    with _lock:
        if namespace is None:
            _said.clear()
        else:
            for key in [k for k in _said if k[0] == namespace]:
                _said.discard(key)
