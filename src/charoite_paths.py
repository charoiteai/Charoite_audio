"""Где лежат рабочие данные Чароита.

Раньше каждый модуль выводил корень из собственного положения:

    ROOT = pathlib.Path(__file__).resolve().parent.parent

Пока код и данные жили в одной папке (склонированный репозиторий), это
работало. С вложенным в приложение python-контуром код переехал внутрь
бандла — а бандл подписан и доступен только на чтение. Писать записи,
стенограммы и логи туда нельзя, да и не нужно: код принадлежит поставке,
данные — человеку.

`CHAROITE_ROOT` разводит одно и другое. Приложение указывает рабочую папку
явно; запуск из репозитория ничего не замечает — без переменной корень
по-прежнему выводится из положения файла.

Корней ДВА, и путать их нельзя:

* `resolve_root()` — корень ДАННЫХ: `transcripts/`, `recordings/`, `logs/`,
  `config/config.yaml`. Слушается `CHAROITE_ROOT`.
* `code_root()` — корень КОДА: `src/`, `scripts/`. Считается от положения
  файла ВСЕГДА и переменную не слушает — код лежит там, где лежит.

Половину контракта знал только Swift-слой, и это стоило дорого: 26 мест
в python ходили за кодом через корень данных (`ROOT / "src" / …`). В
репозитории оба корня совпадают, поэтому дефект был невидим; во вложенной
установке `src/` в папке данных нет, и всё это молча умирало — включая
восстановление оборванной встречи, после чего ретеншн добивал её запись
(аудит 0.46.0, P0-2 и P0-8).
"""
from __future__ import annotations

import hashlib
import os
import pathlib
import threading


#: Корень данных, НАЗВАННЫЙ точкой входа. Пока не назван — выводится, как
#: раньше. Владелец здесь, а не у потребителя: корень один на процесс, и
#: спрашивают его все слои. Пока сеттер стоял в графовом модуле, процесс мог
#: разъехаться сам с собой — граф читал названный корень, а слой моделей
#: выводил свой из положения файла (круг 1 по коду №327, DS C2).
_given: pathlib.Path | None = None

#: Проверка «корень уже назван?» и запись — одно действие. Потоки у демона
#: есть, и два вызова без замка оба увидели бы «не назван»: победил бы
#: последний, ровно тот тихий второй корень, который отказ и запрещает
#: (круг 2 по коду №327, DS M1).
_lock = threading.Lock()

#: Публикация корня для детей — пара «опубликовать/отозвать», а не отметка
#: «моё значение». Отличать своё эхо ПО ЗНАЧЕНИЮ нельзя: приложение ставит
#: переменную до старта, канон записывает туда же нормализованный тот же
#: путь, и дальше они равны по построению — маскируя эхо, сброс выбрасывал
#: заодно решение владельца, и процесс уходил на корень КОДА, то есть в
#: бандле на подписанный read-only `.app` (круг 5 по коду №327, DS C1).
#: Поэтому помним ДВЕ вещи: опубликовали ли мы что-нибудь и что лежало в
#: переменной до первой публикации.
_published: str | None = None
_before_env: str | None = None


def normalize_root(path) -> pathlib.Path:
    """Значение от человека → абсолютный корень данных. Пусто — отказ.

    Одно правило нормализации на проект. Пустая и пробельная строка — не
    путь: `pathlib.Path("").resolve()` это текущий каталог процесса, а
    `Path(" ")` — подкаталог с пробелом в имени. Обе догадки молча уводят
    записи, стенограммы и граф туда, откуда запустили, — ровно дефект
    карточки №36, из-за которого граф писался в одно место, а искался в
    другом. Отказ громче ошибки в пути (круг 1 по коду №327, обе головы).

    Вырожденная точка отсекается отдельно, и это не перестраховка:
    `pathlib.Path("")` — это уже `PosixPath('.')`, объект истинный, и до
    проверки «пусто» доезжает строка `"."`. То есть пустое значение,
    завёрнутое в `Path` где-то по дороге (типовая форма для скриптов:
    `Path(os.environ.get("CHAROITE_ROOT", ""))`), проходило гейт, который
    для той же пустой строки отказывал (круг 2 по коду №327, GLM I1).
    """
    s = str(path or "").strip()
    if not s or s == ".":
        raise ValueError(
            "корень данных не задан: пустое значение — не путь, а текущий "
            "каталог процесса")
    return pathlib.Path(s).expanduser().resolve()


def use_data_root(path, *, replace: bool = False) -> pathlib.Path:
    """Точка входа называет корень данных процесса.

    Пока код и данные лежали в одном дереве, корень можно было вывести из
    положения файла. Отдельно поставленный пакет так не может: рядом с ним
    `site-packages`, а не чужие встречи и конфиг. Выведенный оттуда путь —
    не ошибка в вычислении, а ответ на другой вопрос: где лежит КОД.

    Корень уезжает и в окружение: дети процесса (ночные скрипты, индексатор,
    облачный воркер) считают его сами и иначе судили бы о живой встрече по
    чужому `logs/daemon.lock`. Окружение — единственный канал, общий с
    детьми (круг 1 по коду №327, DS I2).

    Второй вызов с ДРУГИМ корнем — отказ, а не тихая перезапись: объекты,
    собранные до него, продолжают писать в старый каталог, а собранные
    после — читать новый. Писатель в одном месте, читатель в другом — тот
    же класс, что и №36. Повтор с тем же значением безвреден и разрешён.

    Действующим корень делает не только эта запись: `CHAROITE_ROOT` ставит
    приложение ещё до старта, и от неё уже посчитаны пути в модулях, которые
    импортировались раньше. Сравнивать только со своей записью мало — при
    пустой записи второй корень проходил молча, и процесс получал два
    (круг 2 по коду №327, DS C2).

    `replace=True` — смена без окна: снятие старого и запись нового идут под
    одним замком, поэтому состояния «корня нет вовсе» не возникает ни на миг
    (промежуток между «забыть» и «назвать» отвечал бы корнем КОДА — в
    бандловой установке это подписанный read-only `.app`, куда ребёнок из
    этого окна попробовал бы писать; круг 3 по коду №327, DS I1).

    Ключ — для тестов и будущего реплея стадий (№324), и в тексте отказа он
    НЕ упомянут сознательно: рецепт в сообщении об ошибке читается как
    разрешение, и разработчик, наткнувшийся на охранник, обходит его вместо
    того, чтобы понять, почему корень уже назван. Объекты, собранные до
    смены, продолжают писать по старому пути — охранник заведён ровно от
    этого (круг 4 по коду №327, DS I1).
    """
    root = normalize_root(path)
    with _lock:
        global _given
        действующий = None if replace else (_given or _from_env())
        if действующий is not None and действующий != root:
            raise RuntimeError(
                f"корень данных процесса уже назван ({действующий}), второй "
                f"({root}) разошёлся бы с уже отведёнными путями")
        global _published, _before_env
        if _published is None:                 # первая публикация в процессе
            _before_env = os.environ.get("CHAROITE_ROOT")
        _given = root
        _published = str(root)
        os.environ["CHAROITE_ROOT"] = _published
    return root


def forget_data_root() -> None:
    """Отозвать публикацию корня: переменная — как до неё, процесс — без корня.

    Дверь для тех, кто следом называет корень заново или заканчивает работу:
    тест между прогонами, утилита на выходе. Штатная смена корня идёт не
    через неё, а через `use_data_root(..., replace=True)` — там окна без
    корня не бывает.

    Дверь отзывает ПУБЛИКАЦИЮ: в переменной снова оказывается то, что лежало
    там до первой записи канона — решение приложения, если оно было, и ничего,
    если его не было. Это и есть возврат мира в состояние до вызова:

    * процесс, которому корень назвало приложение, после сброса продолжает
      отвечать корнем приложения — а не корнем КОДА, куда его уводила
      прежняя попытка маскировать своё эхо по значению (круг 5, DS C1);
    * процесс, назвавший корень сам, после сброса не знает его — и волен
      назвать заново (круг 4, DS C1);
    * дети в обоих случаях получают то же, что получили бы без нашей
      публикации (круг 3, DS I1).
    """
    global _given, _published
    with _lock:
        _given = None
        if _published is not None:
            # Возвращаем только СВОЮ запись: если между публикацией и отзывом
            # в переменную положил кто-то третий, его значение — не наше дело.
            # Безусловный откат выбрасывал бы чужую запись (при пустом
            # `_before_env` — вовсе), а это новый класс «чужое пропало»
            # (круг 6 по коду №327, DS I1).
            if os.environ.get("CHAROITE_ROOT") == _published:
                if _before_env is None:
                    os.environ.pop("CHAROITE_ROOT", None)
                else:
                    os.environ["CHAROITE_ROOT"] = _before_env
            _published = None


def _from_env() -> pathlib.Path | None:
    """Корень из окружения; пусто и пробельное — не задан.

    Что лежит в переменной — то и действует: пока публикация канона не
    отозвана, там его значение, после отзыва — то, что было до неё.
    Различать своё и чужое ПО ТЕКСТУ невозможно, и попытка это делать стоила
    круга (DS C1 круга 5).
    """
    env = (os.environ.get("CHAROITE_ROOT") or "").strip()
    return pathlib.Path(env).expanduser().resolve() if env else None


def resolve_root(module_file: str) -> pathlib.Path:
    """Корень ДАННЫХ для модуля.

    Порядок: названный точкой входа → `CHAROITE_ROOT` → положение файла.
    Названный сильнее переменной: он единственный не догадка. Вывод из
    положения остаётся последним и верен, только пока модуль лежит в дереве
    репозитория.

    `module_file` — `__file__` вызывающего: он даёт прежнее поведение, когда
    ни корень не назван, ни переменная не задана. Пустое значение переменной
    считаем незаданным: `CHAROITE_ROOT=` в окружении иначе увёл бы все пути
    в текущий каталог.
    """
    if _given is not None:
        return _given
    из_окружения = _from_env()
    if из_окружения is not None:
        return из_окружения
    return pathlib.Path(module_file).resolve().parent.parent


def code_root(module_file: str) -> pathlib.Path:
    """Корень КОДА для модуля: папка, в которой лежат `src/` и `scripts/`.

    `CHAROITE_ROOT` здесь не спрашивается сознательно. Это и есть весь смысл
    функции: путь к соседнему модулю или скрипту обязан считаться от того
    файла, который его зовёт, а не от папки с данными пользователя. Оба
    вызывающих слоя (`src/*.py` и `scripts/*.py`) лежат на одну ступень ниже
    корня, поэтому правило одно на двоих.
    """
    return pathlib.Path(module_file).resolve().parent.parent


#: Корень кода: `CODE_ROOT / "src"`, `CODE_ROOT / "scripts"`.
CODE_ROOT = code_root(__file__)


#: Маска прав для всего, что пишет конвейер: владельцу — всё, остальным — ничего.
DATA_UMASK = 0o077

#: Каталоги данных, которые обязаны быть закрыты (относительно корня данных).
PRIVATE_DIRS = ("transcripts", "recordings", "logs", "data", "config", "backups")

#: Имя каталога со снимками графов внутри корня данных.
BACKUPS_DIR = "backups"

#: Имя каталога с моделями внутри корня ДАННЫХ. Модели — не поставка: `/models/`
#: стоит в .gitignore, в подписанный бандл они не попадают, качает их скрипт
#: моделей при первом запуске. Развилка «модели — данные или код» решается здесь
#: один раз: пока её не было, диаризация искала их от корня данных, а NLI-слой от
#: корня кода, и во вложенной установке второй молча не находил ничего.
MODELS_DIR = "models"


def harden_umask() -> int:
    """Закрыть от посторонних всё, что процесс создаст дальше.

    Стенограмма встречи — это и есть чувствительные данные продукта, а
    штатный umask 022 отдавал их с правами 0644: на машине с несколькими
    учётками любой второй пользователь читал чужие переговоры целиком
    (аудит 16.08). Маска ставится один раз в точке входа и действует на
    всё, что процесс откроет потом, — включая файлы, которые создают
    сторонние библиотеки (кэши моделей, индексы).

    Возвращает прежнюю маску — на случай, если вызывающему нужно вернуть.
    """
    return os.umask(DATA_UMASK)


def secure_dir(path: pathlib.Path) -> pathlib.Path:
    """Создать каталог данных и убедиться, что он закрыт (0700).

    `mkdir(mode=)` не помогает для уже существующего каталога, а именно
    такие остались у всех, кто ставил Чароит до этой правки, — поэтому
    права выставляются всегда, а не только при создании.
    """
    path.mkdir(parents=True, exist_ok=True)
    try:
        path.chmod(0o700)
    except OSError:
        pass  # каталог может лежать на ФС без прав (iCloud, сетевой том)
    return path


def graph_backups(graph: pathlib.Path, kind: str = "cloud_backup",
                  root: pathlib.Path | None = None) -> pathlib.Path:
    """Куда класть служебные снимки графа — ВНЕ синхронизируемой папки.

    Раньше снимок ложился внутрь самого графа (`<граф>/.cloud_backup/`), а
    граф живёт в iCloud. Каждая облачная правка копирует граф целиком, и к
    21.08 в хранилище Обсидиана лежало 48 122 служебных файла на 1.7 ГБ —
    из 58 260 файлов и 1.9 ГБ всего архива. Синхронизировать этот балласт
    круглосуточно пытались `fileproviderd` (127% CPU), `bird`, `fseventsd`
    и `filecoordination`: больше двух ядер уходило в никуда, а живой записи
    в это время не хватало процессора — стенограмма отставала и рвалась.

    Снимок — служебные данные конвейера, ему место рядом с `logs` и `data`:
    те же права 0700, никакой отправки в облако. Имя графа берём у самой
    папки, чтобы снимки разных графов не смешались.
    """
    g = pathlib.Path(graph).resolve()
    # Имя + хеш ПОЛНОГО пути: два графа «Работа» из разных vault иначе
    # делили бы один каталог — ротация одного стирала бы снимок другого,
    # а restore возвращал бы файлы чужого графа (круг по PR #363, DeepSeek).
    digest = hashlib.sha256(str(g).encode("utf-8")).hexdigest()[:8]
    base = (root or resolve_root(__file__)) / BACKUPS_DIR / f"{g.name}-{digest}"
    return base / kind


def harden_existing(root: pathlib.Path | None = None) -> int:
    """Закрыть уже созданные данные: каталоги 0700, файлы 0600.

    Разовая миграция для установок, живших со старой маской. Считает,
    сколько путей поправила; ошибки прав на отдельных файлах не должны
    ронять запуск — встреча важнее.
    """
    base = root or resolve_root(__file__)
    fixed = 0
    for name in PRIVATE_DIRS:
        d = base / name
        if not d.exists():
            continue
        for p in [d, *d.rglob("*")]:
            try:
                want = 0o700 if p.is_dir() else 0o600
                if (p.stat().st_mode & 0o777) != want:
                    p.chmod(want)
                    fixed += 1
            except OSError:
                continue
    return fixed


# Бессрочные append-логи (mlx_server.log, daemon.err.log) росли без потолка:
# у долгоживущей установки это гигабайты кусков стенограмм на диске (аудит
# 16.08, п.7). Потолок — при старте, хвост сохраняется: именно он нужен для
# диагноза последнего сбоя.
LOG_MAX_BYTES = 20 * 1024 * 1024
LOG_KEEP_BYTES = 2 * 1024 * 1024


def trim_log(path: pathlib.Path, max_bytes: int = LOG_MAX_BYTES,
             keep_bytes: int = LOG_KEEP_BYTES) -> bool:
    """Усечь лог до хвоста, если он перерос max_bytes. True — усекали.

    Хвост режется по границе строки, чтобы первая строка не была
    обрывком; права файла не трогаются (он уже 0600). Ошибки — не повод
    ронять запуск: лог важнее отсутствия лога, но встреча важнее лога.
    """
    try:
        size = path.stat().st_size
    except OSError:
        return False
    if size <= max_bytes:
        return False
    try:
        with path.open("rb") as f:
            f.seek(size - keep_bytes)
            tail = f.read()
        cut = tail.find(b"\n")
        if 0 <= cut < len(tail) - 1:
            tail = tail[cut + 1:]
        # Через временный файл и rename: упасть между truncate и записью —
        # остаться без хвоста, ради которого всё и затевалось (круг-1 по
        # PR #377, qwen). Права — 0600 явно, не по umask вызывающего.
        tmp = path.with_name(path.name + ".trim")
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        os.fchmod(fd, 0o600)   # режим в os.open действует только при создании
        with os.fdopen(fd, "wb") as f:
            f.write(f"[лог усечён при старте: было {size} байт]\n".encode("utf-8"))
            f.write(tail)
        os.replace(tmp, path)
        return True
    except OSError:
        return False

