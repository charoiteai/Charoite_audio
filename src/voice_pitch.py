"""Регистр голоса по частоте основного тона — чтобы не назвать мужчину Анной.

Опознание имён работает с текстом: кто-то произнёс «Анна», лёгкая модель
решила, что так зовут говорящего, и метка переписалась задним числом по всей
встрече. Голос при этом басовитый, но опознание про голос не знает ничего.

Здесь считается одна величина — медианная частота основного тона говорящего —
и переводится в «низкий регистр / высокий / не знаю». Этого достаточно, чтобы
отклонить явное противоречие между голосом и родом имени, и недостаточно,
чтобы кого-то классифицировать: продукт не приписывает людям пол и не пишет
его ни в стенограмму, ни в граф. Регистр живёт в памяти встречи и исчезает
вместе с ней — как и эмбеддинги голосов (PRIVACY.md).

Почему пороги такие осторожные. Мужской диапазон F0 — примерно 85-180 Гц,
женский — 165-255; между ними полоса, где одна лишь частота не решает: там
работают форманты, и точность распознавания на слух в ней заметно падает.
Поэтому регистр считается определённым только ЗА пределами этой полосы, а
внутри честно возвращается None — гейт тогда просто не срабатывает.

Асимметрия ошибок сознательная: ошиблись — потеряли имя (осталось
«Собеседник 2»), а не подписали человека чужим. Потерянное имя дописывается
позже, неверное живёт в графе месяцами.

Без новых зависимостей: автокорреляция на numpy, который уже нужен аудио.
"""
from __future__ import annotations

import numpy as np

# Границы поиска основного тона: ниже 70 Гц человеческая речь не живёт, выше
# 320 — это уже не разговорный голос взрослого.
F0_MIN, F0_MAX = 70.0, 320.0

# Края «андрогинной зоны». Ниже LOW_MAX голос уверенно низкий, выше HIGH_MIN —
# уверенно высокий, между — не знаем и не гадаем.
LOW_MAX = 145.0
HIGH_MIN = 190.0

# Меньше этого куска мерить нечего: на 0.2с автокорреляция ловит случайный
# период, а не голос.
MIN_SECONDS = 0.25
# Сколько секунд чанка реально анализируем. Основной тон за полсекунды не
# меняется, а чанк приходит трёхсекундный — считать по всему значит платить
# втрое ни за что.
ANALYSE_SECONDS = 0.5
# Сколько кусков нужно, чтобы говорить о регистре ГОВОРЯЩЕГО, а не о чанке.
MIN_CHUNKS = 2


def estimate_f0(chunk: np.ndarray, sample_rate: int) -> float | None:
    """Частота основного тона куска речи в герцах. None — тона нет.

    Автокорреляция: у голоса она даёт выраженный пик на периоде основного
    тона. Шум, тишина и щелчки такого пика не дают — возвращаем None вместо
    выдуманного числа.
    """
    if chunk is None or sample_rate <= 0:
        return None
    x = np.asarray(chunk, dtype=np.float64).ravel()
    if x.size < int(MIN_SECONDS * sample_rate):
        return None
    # Полсекунды хватает: основной тон за это время не меняется, а считать
    # автокорреляцию по трёхсекундному чанку — платить втрое за тот же ответ.
    x = x[:int(ANALYSE_SECONDS * sample_rate)]
    x = x - x.mean()
    energy = float(np.sqrt(np.mean(x * x)))
    if energy < 1e-4:
        return None                 # тишина

    # Автокорреляция через FFT: прямая np.correlate — O(n²), и на живой
    # встрече это секунды процессорного времени на каждый чанк вместо
    # миллисекунд. Дополняем нулями до степени двойки, чтобы свёртка была
    # линейной, а не круговой.
    size = 1 << int(np.ceil(np.log2(2 * x.size)))
    spec = np.fft.rfft(x, size)
    corr = np.fft.irfft(spec * np.conjugate(spec), size)[:x.size]
    if corr[0] <= 0:
        return None
    corr = corr / corr[0]

    lo = int(sample_rate / F0_MAX)
    hi = min(int(sample_rate / F0_MIN), corr.size - 1)
    if hi <= lo:
        return None
    window = corr[lo:hi]
    peak = int(np.argmax(window)) + lo
    # Слабый пик — это не периодический сигнал: у речи он заметный.
    if corr[peak] < 0.3:
        return None
    return float(sample_rate) / float(peak)


def register(f0: float | None) -> str | None:
    """«low» / «high» / None — регистр по частоте, без гадания в середине."""
    if f0 is None:
        return None
    if f0 <= 0 or not (F0_MIN <= f0 <= F0_MAX):
        return None
    if f0 < LOW_MAX:
        return "low"
    if f0 > HIGH_MIN:
        return "high"
    return None                     # андрогинная зона: частота не решает


def speaker_register(chunks: list[np.ndarray], sample_rate: int) -> str | None:
    """Регистр говорящего по нескольким кускам его речи.

    Медиана, а не среднее: один выкрик выше обычного (смех, вопрос в конце
    фразы) не должен переводить человека в другой регистр. Мало кусков —
    ответа нет: на одном могут ошибиться и люди.
    """
    values = [f for f in (estimate_f0(c, sample_rate) for c in chunks) if f]
    if len(values) < MIN_CHUNKS:
        return None
    return register(float(np.median(values)))


def contradicts(voice: str | None, name_gender: str | None) -> bool:
    """Уверенно ли расходятся голос и род имени.

    True только когда обе стороны определённы и противоположны. Всё
    остальное — включая «unisex» («Саша», «Женя») и любое «не знаю» —
    поводом отказать не является.
    """
    if voice not in ("low", "high"):
        return False
    if name_gender not in ("male", "female"):
        return False
    return (voice == "low" and name_gender == "female") or \
           (voice == "high" and name_gender == "male")
