"""Правила автотезисов: системный промпт и фильтр ответа модели.

Вынесены из daemon.py, чтобы тестироваться без аудио: daemon при импорте
тянет sounddevice, и тест на фильтр строк платил бы за это микрофоном.

💎 «ценная информация» убран (03.08): факты разговора теперь несёт нить —
она пишет их под темами и с дедупом, и третий поток тех же фактов в ленте
тезисов стал дублированием. Остались 📌 (контрольная точка: решение, срок,
поручение — то, за что отвечают) и 💭 (мысль модели — то, чего в разговоре
не прозвучало).
"""

from __future__ import annotations

# Знаки живых тезисов. LEGACY шире: 💎 остался в записях прошлых встреч
# на диске, и чистка/дедуп обязаны его узнавать.
PREFIXES = ("📌", "💭")
LEGACY_PREFIXES = ("📌", "💎", "💭")

THINK_SYSTEM = (
    "Ты — второй мозг владельца на рабочей встрече: думаешь вместе с ним по живой стенограмме. "
    "Из НОВОГО фрагмента выдели только по-настоящему ценное, каждое с новой строки со строгим префиксом:\n"
    "📌 — контрольная точка: решение, договорённость, срок, поручение (кто/что/когда)\n"
    "💭 — твоя мысль (максимум одна): противоречие со сказанным ранее, упущенный вопрос, скрытый риск\n"
    "Просто факты, цифры и имена НЕ выписывай — их ведёт другой контур. "
    "ИГНОРИРУЙ фоновое медиа: радио, телевизор, ролики, новости, политика, "
    "реклама — всё, что явно не разговор присутствующих о работе. Из такого "
    "фрагмента тезисы не делай (21.07: «поручение» из новостного эфира "
    "попало в контрольные точки).\n"
    "Телеграфно, по-русски. Если ничего ценного не прозвучало — ответь ровно: NONE"
)


def parse(out: str) -> list[str]:
    """Строки тезисов из ответа модели — только с живым префиксом.

    Модель любит вступления («Вот что важно:») и по старой памяти шлёт 💎 —
    строка без валидного префикса в ленте выглядит как реплика участника,
    поэтому отбрасывается целиком, как и NONE.
    """
    lines: list[str] = []
    for raw in out.strip().splitlines():
        line = raw.strip()
        if not line or line.upper().startswith("NONE"):
            continue
        if line.startswith(PREFIXES):
            lines.append(line)
    return lines


def strip_mark(line: str) -> str:
    """Текст тезиса без знака — для сравнения на дубли."""
    return line.lstrip("".join(LEGACY_PREFIXES) + " ").strip()
