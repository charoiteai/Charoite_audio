"""Коды возврата, читаемые через границу процесса, — одно место без импортов.

Их читают три стороны: сам graph_updater (sys.exit), пересборка
(rebuild_transcript) и импорт внешней записи (import_meeting). Импорт —
короткоживущий ребёнок на каждый файл, и тянуть ради двух чисел верхний
уровень graph_updater (requests, llm_health) ему было дорого, поэтому он
держал копию литералов 3/4. Копия расходится молча: перенумерация в
graph_updater превратила бы «нет речи» в «ошибка + retro_fill по всему
бэклогу» (критика GLM r2 по #502, №173). Модуль намеренно без импортов —
его можно тянуть из любого места, не оплачивая чужие зависимости.
"""

#: «В записи нет речи» — не ошибка конвейера, а его честный результат.
#: Вызывающий отличает это от падения по коду возврата и не ставит повтор.
EXIT_NO_SPEECH = 3
#: Модель не дала JSON: узлы графа не обновлены, но архив, копии в vault,
#: облачный разбор и хук собраны. Пересборка по этому коду помечает встречу
#: ошибкой и вернётся к ней (retry_unfinished), а не пишет «готово».
EXIT_NO_GRAPH = 4

#: Точка входа не получила корня данных: запускавший не сказал, где они
#: лежат. Не «упал», а «не начал» — повтор без правки окружения бесполезен,
#: и launchd с KeepAlive обязан видеть это кодом, а не нулём (№332). Не 2:
#: код 2 отдаёт argparse на ошибке аргументов и любой общий `sys.exit(2)`,
#: и проба контракта запуска не отличила бы отказ канона от опечатки во
#: флаге (круг 1 по коду №339, DS C1).
EXIT_ROOT_UNNAMED = 5

#: Инструмент проверки отработал, но проверять было НЕЧЕГО: в диапазоне нет
#: наших python-строк. Это не «всё хорошо»: приёмка обязана сказать «неполно»,
#: а не «ok». Прежде этот исход возвращал 0 и различался подстрокой в выводе —
#: приёмка ключевалась на текст и зеленела при нуле проверок (круг 2 по коду
#: №339, DS C1).
EXIT_NOTHING_TO_CHECK = 6

#: Проверка НАЧАЛАСЬ, но прошла не вся: прогон прерван живой встречей или ночью,
#: часть работы срезана потолком, часть мутантов не применилась. Это не «чисто»
#: и не «дыра» — это «судили подмножество», и приёмка обязана сказать «неполно».
EXIT_PARTIAL = 7

#: Изменённые строки ЕСТЬ, а мутировать в них нечего. Отдельно от «строк нет»:
#: под одним кодом они неразличимы, и 25.09 правка условия, для которой в
#: мутаторе не нашлось оператора, прошла CI с «мутировать было нечего» — ноль
#: мутантов читался как пустой диапазон (№386).
EXIT_UNMUTABLE = 8

#: Что означает код возврата инструмента проверки. Один классификатор на всех
#: потребителей (приёмка, CI, ночь): до него каждый круг добавлял своё
#: сопоставление — подстрока в выводе, потом цифра, потом grep по «СРЕЗАНО», —
#: и «0» означал четыре разные вещи: «проверено и чисто», «нечего проверять»,
#: «прервано», «судили часть» (круг 3 по коду №339, DS C1 и «Как чинить»).
def outcome(rc: int) -> str:
    """`ok` — проверено полностью и чисто; `nothing` — проверять было нечего;
    `unmutable` — строки есть, ломать в них нечего; `partial` — проверено не
    всё; `fail` — найден дефект или сломалась сама проверка. Имена — для
    сводки человеку, значения — для гейтов."""
    if rc == 0:
        return "ok"
    if rc == EXIT_NOTHING_TO_CHECK:
        return "nothing"
    if rc == EXIT_PARTIAL:
        return "partial"
    if rc == EXIT_UNMUTABLE:
        return "unmutable"
    return "fail"
