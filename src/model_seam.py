"""Шов способности: чем граф считает векторы, не зная, кто их считает.

Графовый слой держит индекс и решает, что на что похоже; слой моделей знает
Ollama, имена моделей и таймауты. Между ними — значение, а не импорт: поиск
получает готовый векторизатор параметром и не может спросить, откуда тот взялся.

Почему пара, а не две вещи рядом. Имя модели — не украшение вызова: под ним
подписан дисковый кэш векторов (`GraphSearch.cache_key`). Пока функция и имя
ехали двумя независимыми параметрами, можно было передать функцию одной модели
и имя другой: векторы чужого пространства легли бы под привычным именем, и
косинус запроса против такого кэша — шум, а не свидетельство. Одним значением
расхождение нечем выразить.

Модуль лежит в нижнем слое сознательно. Тип нужен обоим берегам — и тому, кто
способность строит, и тому, кто её получает, — а значит не может жить ни у
одного из них: импорт ради аннотации восстановил бы ровно то ребро, которое
шов и снимает (гейт раскладки считает импорты обходом всего дерева, включая
`if TYPE_CHECKING`). Зависимостей у модуля нет и быть не должно: его читает и
`scripts/doctor.py`, который обязан печатать рецепт на машине, где ещё нечем
ходить в сеть.
"""
from __future__ import annotations

import dataclasses
from typing import Callable

#: Модель эмбеддингов по умолчанию. Не страховка, а боевое значение: ключа
#: `sufler.embed_model` нет ни в одном конфиге поставки, поэтому именно эта
#: строка подписывает дисковые кэши всех установок. Менять её — переиндексация
#: графа у каждого, у кого он уже собран.
DEFAULT_EMBED_MODEL = "bge-m3:latest"

#: Имя пустого векторизатора. Своё, не боевое: под именем подписаны и кэш на
#: диске, и индекс в процессе, так что «моделей нет» обязано отличаться от
#: «bge-m3» — иначе первый позвавший без конфига застолбит индекс графа, а
#: пришедший следом с настоящим конфигом молча получит его (круг 1 по коду,
#: DS I2). Скобки в имени делают его непохожим на модель Ollama намеренно.
NO_MODEL = "(моделей нет)"


def embed_model_name(cfg: dict, model: str | None = None) -> str:
    """Чем считаем векторы: явное имя, конфиг владельца или дефолт поставки.

    Единственный резолвер на проект — и живёт он здесь, а не рядом с
    транспортом, потому что имя спрашивают оба берега и диагностика. У доктора
    выбора нет вовсе: слой моделей тянет `requests`, а доктор обязан печатать
    рецепт на машине, где ставить пакеты ещё нечем.

    Раньше эта строчка жила в трёх местах — слой моделей, ключ дискового кэша
    поиска, контур дежавю, — и каждая копия была отдельной возможностью
    разойтись. Имя подписывает кэш векторов: расхождение стоит не ошибки, а
    часов пересчёта у каждого владельца.
    """
    return str(model or (cfg.get("sufler") or {}).get("embed_model") or DEFAULT_EMBED_MODEL)


class SeamTransportError(OSError):
    """Способность не сработала по причине, которая потребителя не касается.

    Сеть, занятый сервер, запрещённый политикой адрес — для графа это один
    исход: векторов нет, идём лексикой. Раньше потребитель перечислял типы
    исключений чужого слоя и обязан был угадать их таксономию; угадал не всё —
    `RuntimeError` от политики адреса летел мимо и превращался в «память ещё
    прогревается» навсегда (круг 1 по коду, обе головы).

    Теперь перечисляет поставщик, у которого это знание и есть, а граф ловит
    один объявленный класс. Наследование от `OSError` — чтобы потребитель,
    ловящий транспорт по-старому, не сломался.

    `policy` отделяет «нельзя по настройке владельца» от «сервер не ответил»:
    для контура это один исход, а для человека — разные слова. Называть отказ
    его собственной настройки «модель занята» значит отправить его чинить не
    то (круг 2 по коду, DS I3).
    """

    def __init__(self, message: str, *, policy: bool = False) -> None:
        super().__init__(message)
        self.policy = policy


@dataclasses.dataclass(frozen=True)
class Embedder:
    """Векторизатор и имя, под которым он считает.

    `run(texts, timeout)` отдаёт по вектору на текст. Контракт исходов узкий,
    и потребитель на него полагается:

    * векторы — всё хорошо;
    * пустой список — сервер ответил, но векторов не дал (модели нет, занят);
    * `SeamTransportError` — не сработало по своей причине: сеть, занятый
      сервер, запрещённый политикой адрес. Потребитель гасит это в лексику:
      подсказка на встрече важнее семантики.

    Всё остальное (`TypeError`, `AttributeError`) — ошибка проводки, а не
    деградация, и обязано долетать до человека. Ловить их «на всякий случай»
    значит неделями отдавать подсказки без семантики, ни разу не крикнув.

    Пару собирает фабрика слоя моделей (`llm.embedder`): она одна знает и
    транспорт, и то, как резолвится имя. Собранная руками пара законна ровно в
    тестах, где обе половины пишет один человек в одной строке.
    """

    run: Callable[[list[str], float], list[list[float]]] = dataclasses.field(repr=False)
    model: str
    #: Почему способности не будет, если это известно уже при сборке. Пустая
    #: строка — всё в порядке. Отказ политики адреса виден фабрике сразу, а
    #: потребитель узнал бы о нём только с первым вектором — которого на
    #: пустом кэше не бывает вовсе, и владельцу называлась чужая причина
    #: («сервер занят» вместо «вы запретили этот адрес»). Исход принадлежит
    #: способности, а не тому, кто её звал (круг 3 по коду, обе головы).
    refused: str = ""
