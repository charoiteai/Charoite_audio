def _norm(word: str) -> str:
    return word.strip().casefold().replace("ё", "е")


def _stem(word: str) -> str:
    return _SOFT_TAIL.sub("", word)


def _split_names(text: str) -> list[str]:
    """Перечисление исполнителей → имена, без союзов и пустых кусков."""
    return [x.strip() for x in _NAME_SEP.split(text or "") if x.strip() and _norm(x) not in _JOINERS]


def participants_set(names, owner: str = "") -> set[str]:
    """Имена в множество участников: заглушки («Собеседник 2», «Speaker 1»,
    «Я») и пустые отбрасываются, владелец добавляется. Пусто — участники
    неизвестны, и судить некого."""
    out: set[str] = set()
    for raw in names or ():
        name = str(raw or "").strip()
        if name and not _PLACEHOLDER.match(name):
            out.add(name)
    if owner and owner.strip():
        out.add(owner.strip())
        # И формы каждого слова владельца («Павлу», «Льву», «Ковалёвой»): «Павлу»
        # у владельца-Павла flag_outsiders участником не считал (_same_person не
        # знает беглой гласной), и легаси-строка минуток теряла чекбокс при
        # дописывании мостом (Important GLM r3 по #536). Факт «это владелец» —
        # в данных, а не только в порядке вызовов finalize_assignees. Только при
        # известных собеседниках: один участник — гейт «судить некого» в
        # flag_outsiders считает строки, и формы не должны его отпирать.
        if len(out) >= 2:
            for word in owner.split():
                out.update(_owner_forms(word))
    return out


def participants_of(transcript: str, owner: str = "") -> set[str]:
    """Участники из ТЕКСТА стенограммы в формате файла: шапка «Участники
    (звучали в разговоре): …» (роли в скобках срезаются) и метки говорящих
    «**Имя** [чч:мм]». Для живого объекта Transcript этот текст не годится —
    брать Transcript.participants() и participants_set()."""
    names: list[str] = []
    text = transcript or ""
    m = _PARTICIPANTS_HEAD.search(text)
    if m:
        head = re.sub(r"\s*[(（].*?[)）]", "", m.group(1))
        names += [x.strip() for x in head.split(",") if x.strip()]
    names += [lab.strip() for lab in _SPEAKER_LABEL.findall(text)]
    return participants_set(names, owner)


def same_case_form(word: str, known_word: str) -> bool:
    """Одно имя в разных падежах или то же слово — БЕЗ таблицы уменьшительных.

    Для склейки (дедуп моста ревизии, снятие поручений), где цена ошибки —
    съеденное поручение: «Сергею»/«Сергей», «Ивану Орлову»/«Иван Орлов» —
    да; «Вере»/«Веронике», «Славе»/«Ярославу» — нет (Critical DS/GLM по #536
    для владельца, DS Critical по #553 для остальных). Коллизия «Витя»/«Вита»
    (одна основа) остаётся принятой ценой. Правила — первые два из
    _same_person; уменьшительные там же, третьим."""
    word, known_word = _norm(word), _norm(known_word)
    if word == known_word:
        return True
    a, b = _stem(word), _stem(known_word)
    if len(a) >= 2 and a == b:
        return True
    short, long = sorted((a, b), key=len)
    return len(short) >= 3 and long.startswith(short) and _CASE_TAIL.fullmatch(long[len(short):]) is not None


def _same_person(word: str, known_word: str) -> bool:
    """Одно имя в разных падежах, уменьшительное к полному, или то же слово.

    Основы без последней мягкой буквы равны («саше»/«саша» → «саш»); или
    одна основа — другая плюс падежный хвост из гласных и «м» («ольго» =
    «ольг» + «о»: «Ольгой»; «игорем» = «игор» + «ем»). «Марине» и «Мария»
    («марин» / «мари» + «н») — разные люди: голый 4-буквенный префикс их
    склеивал (GLM, круг 1 #510). Известные коллизии этой эвристики —
    «Витя»/«Вита» (одна основа) и «Ветровой»/«Ветров» (хвост «ой» падежный)
    — приняты: цена ошибки здесь «задача осталась», а не «задача пропала».
    ё и е — одна буква (DS M3, круг 2)."""
    if same_case_form(word, known_word):
        return True
    word, known_word = _norm(word), _norm(known_word)
    # уменьшительное ↔ полное, в любом падеже: сравниваем основы
    for small, full_names in ((word, known_word), (known_word, word)):
        fulls = _DIMINUTIVES.get(small) or _DIMINUTIVES.get(_stem(small) + "а") or _DIMINUTIVES.get(_stem(small) + "я")
        if fulls and any(_stem(_norm(f)) == _stem(full_names) or _stem(full_names).startswith(_stem(_norm(f)))
                         for f in fulls):
            return True
    return False


def _same_people(whole: str, participants: set[str]) -> bool:
    """«Воронин, Женя» — это «Женя Воронин»: тот же набор слов в любом порядке.
    Союзы делают строку перечислением, а не одним человеком: «Дмитрий и
    Ольга» и «Саша и Петров» целиком ни за кого не сходят (DS M4, круг 2)."""
    raw = [w for w in re.split(r"[\s,/;]+", whole.strip()) if w]
    if any(_norm(w) in _JOINERS for w in raw):
        return False
    words = {_norm(w) for w in raw}
    if not words:
        return False
    for p in participants:
        pf = {_norm(w) for w in p.split() if w}
        if pf and pf == words:
            return True
    return False


def _is_participant(name: str, participants: set[str]) -> bool:
    n = _norm(name).strip(".")
    if not n or n in _COLLECTIVE or _PLACEHOLDER.match(n):
        return True    # собирательное или заглушка — не про человека, не судим (GLM M3)
    words = n.split()
    first = words[0]
    initial = re.fullmatch(r"([а-яa-z])\.", first)
    for p in participants:
        pf = _norm(p).split()
        if not pf:
            continue
        if n == " ".join(pf):
            return True
        if initial:
            # «Д. Петров» при «Дмитрий Петров»: инициал совпал с первой буквой
            # какого-то слова участника, а фамилия — с другим (GLM M2)
            rest = words[1:]
            if any(w.startswith(initial.group(1)) for w in pf) and rest and \
                    any(_same_person(r, w) for r in rest for w in pf):
                return True
            continue
        # первое слово исполнителя — против КАЖДОГО слова участника: в шапке
        # может стоять «Дмитрий Петров», а в поручении — «Петров» (GLM I3)
        if any(_same_person(first, w) for w in pf):
            return True
    return False


def flag_outsiders(text: str, participants: set[str], lang: str = "ru") -> str:
    """Поручение тому, кого на встрече не было, — пометка, а не задача.

    Строка «- [ ] **Имя** — …» в разделе поручений становится
    «- ⚠ не участник (Имя): **Имя** — …»: без чекбокса её не подхватит окно
    «Задачи», а читающий минутки видит, что исполнителя надо назначить заново
    или передать дальше. Остальные разделы и известные исполнители не
    трогаются. Пустой список участников — ничего не решаем."""
    # Один известный участник — это владелец без опознанных собеседников
    # (1:1 без имён, сорванный разбор имён): судить некого, любое имя из
    # речи — законный исполнитель (GLM I2, круг 2).
    if len(participants) < 2:
        return text
    mark = OUTSIDER_MARKS.get((lang or "ru").strip().lower()[:2], OUTSIDER_MARK)
    out: list[str] = []
    inside = False
    for line in text.split("\n"):
        if is_section_heading(line):
            inside = True
            out.append(line)
            continue
        if inside and ((_OTHER_SECTION.match(line)
                        or (_BARE_HEADING.match(line) and _KNOWN_BARE_SECTION.match(line)))
                       and not _BULLET.match(line)):
            inside = False
        # статус, поставленный человеком или контролем (выполнено, возвращено), пометка
        # «не участник» не снимает: она убирает чекбокс (№366)
        if inside and not task_line.settled(line):
            m = _ASSIGNEE_LINE.match(line)
            if m:
                whole = m.group(2).strip()
                # «Воронин, Женя» — сначала целиком (тот же набор слов), потом по
                # частям (GLM M5); «Дмитрий и Ольга» целиком не сойдёт за Дмитрия
                if _same_people(whole, participants):
                    strangers: list[str] = []
                else:
                    strangers = [x for x in _split_names(whole) if not _is_participant(x, participants)]
                if strangers:
                    line = f"{m.group(1)}- {mark} ({', '.join(strangers)}): **{m.group(2)}**{m.group(3)}"
        out.append(line)
    return "\n".join(out)


# ---- исполнитель-владелец — одним написанием ---------------------------------
# Минутки и мост ревизии пишут имя так, как оно прозвучало: «Игорю», «Петр»
# без ё. Окно «Задачи» узнаёт владельца по ЦЕЛОМУ слову user_name
# (TasksScreenPolicy.isMine — намеренно без эвристик: «Маркус» ≠ «Марк»), и
# такая форма выпадала из секции «Мои». Решение «это владелец» принимается
# здесь, при записи поручения, и в одном месте на все четыре пути записи
# (черновик и финал демона, sufler_make_minutes, пересборка) и мост ревизии (№188).
# Правило нарочно узкое. Первая версия сравнивала через _same_person (падеж,
# уменьшительные, фамилия) — и склеивала «Александре» (дательный женского
# имени) с владельцем-Александром, «Вите» с Виктором, «Ковалёвой» с Ковалёвым,
# «Вере» с Вероникой (Critical DS и GLM, круг 1 по #536). У сверки участников
# цена такой ошибки — «задача осталась», здесь — «чужая задача сменила
# исполнителя в файле». Поэтому: только ОДНО слово исполнителя, только ИМЯ
# владельца (первое слово user_name), и только формы, которые выводятся из
# самого имени, — именительный, дательный («Марку — сделать») и написание
# через «е» вместо «ё». Фамилия, уменьшительные («Саша» при «Александр»),
# составные исполнители («Марк и Инга», «Марку Ковалёву») не трогаются.
# Известные коллизии, принятые как цена: уменьшительное в самом user_name
# («Витя») и чужая Вита — дательный у обоих «Вите»; фамилия владельца,
# бытующая как имя («Иван Роман»: «Роману» → «Роман»; DS r3) — но такой
# «Роман» и в именительном уже «Мои» у приложения. Фамилия — той же механикой
# (круг 2, критика GLM): «Ковалёву» → «Ковалёв», «Ковалёвой» у владелицы
# Ковалёвой → «Ковалёва», а «Ковалёвой» у владельца Ковалёва — нет;
# однофамилец в дательном неотличим ровно так же, как в именительном.
# Буллет без чекбокса («- **Имя** — …», руками в Obsidian) матчится ради
# сравнения в мосте; на пути записи гейт — _ASSIGNEE_LINE с чекбоксом.
_OWNER_ITEM = re.compile(r"^(\s*(?:[-*] )?(?:\[[ xX]\] )?)\*\*([^*\n]{1,80})\*\*(.*)$")
# Таблицы вместо орфографических правил: класс имён с беглой гласной закрыт
# (Павел, Лев), а правило по суффиксу «-ел» давало «Даниел» → «данилу» —
# дательный ДРУГОГО имени (критика GLM r2 по #536). Женские имена на -ь —
# дательный на -и, класс открыт: пополнять таблицу, а не выводить правило.
_FLEETING_STEM = {"павел": "павл", "лев": "льв"}
_DATIVE_EXACT = {"любовь": "любови", "нинель": "нинели", "рахиль": "рахили", "адель": "адели"}


def _owner_forms(word: str) -> set[str]:
    """Формы слова из user_name в позиции исполнителя (в виде _norm: регистр
    и ё/е в обе стороны — «Семёну» при «Семен», «Петр» при «Пётр»):
    именительный и дательный по типу склонения. Генерация из самого слова, а
    не стемминг чужого: «Александре» — дательный женского имени, у
    владельца-Александра дательный — «Александру», и они не путаются."""
    n = _norm(word)
    forms = {n}
    if n in _DATIVE_EXACT:
        forms.add(_DATIVE_EXACT[n])
    elif n.endswith(("ский", "цкий")):
        forms.add(n[:-2] + "ому")                 # Ковальский → Ковальскому
    elif n.endswith("ая"):
        forms.add(n[:-2] + "ой")                  # Ковальская → Ковальской
    elif n.endswith("ия"):
        forms.add(n[:-1] + "и")                   # Мария → Марии
    elif n.endswith(("а", "я")):
        forms.add(n[:-1] + "е")                   # Анна → Анне, Илья → Илье, Наталья → Наталье
        if n.endswith(("ова", "ева", "ина", "ына")):
            forms.add(n[:-1] + "ой")              # Ковалёва → Ковалёвой (женская фамилия; DS r3)
    elif n.endswith(("ь", "й")):
        forms.add(n[:-1] + "ю")                   # Игорь → Игорю, Андрей → Андрею
    else:
        forms.add(_FLEETING_STEM.get(n, n) + "у")   # Марк → Марку, Ковалев → Ковалеву, Павел → Павлу
    return forms


def _owner_canon(whole: str, owner: str) -> str | None:
    """Написание из user_name, если `whole` — одно из его слов в другой форме
    (дательный, регистр, ё/е), иначе None. Имя → имя, фамилия → фамилия:
    «Ковалёву» → «Ковалёв», не «Марк»."""
    canon = [w for w in (owner or "").split() if w]
    if not canon:
        return None
    names = _split_names(whole)
    if len(names) != 1 or len(names[0].split()) != 1:
        return None                       # «Марк и Инга», «Марку Ковалёву» — не трогаем
    word = names[0].strip()
    if word in canon:
        return None                       # уже канон — побуквенно, с регистром
    plain = _norm(word)
    for w in canon:
        if plain in _owner_forms(w):
            return w                      # «марку», «МАРК», «Петр», «Ковалёву» → слово из user_name
    return None


def canon_owner_item(item: str, owner: str) -> str:
    """Один пункт («**Имя** — дело», с чекбоксом или без) с владельцем в каноне."""
    m = _OWNER_ITEM.match(item or "")
    if not m:
        return item
    name = _owner_canon(m.group(2).strip(), owner)
    if name is None:
        return item
    return f"{m.group(1)}**{name}**{m.group(3)}"


def finalize_assignees(text: str, participants: set[str], owner: str, lang: str = "ru") -> str:
    """Исполнители раздела поручений перед записью минуток: сначала владелец
    в каноне, потом пометка «не участник». Порядок — контракт этой функции:
    «Павлу» у владельца-Павла flag_outsiders участником не считает
    (_same_person не знает беглой гласной), и до канона строка не доживала —
    чекбокс снят, canon_owner её уже не видит (Critical DS r2 по #536).
    Один вызов на все четыре пути записи: черновик и финал демона,
    sufler_make_minutes, пересборка (rebuild_transcript)."""
    return flag_outsiders(canon_owner(text, owner), participants, lang=lang)


def canon_owner(text: str, owner: str) -> str:
    """Раздел поручений минуток: слово user_name в другой форме — написанием
    из user_name. Остальные разделы и чужие исполнители не трогаются; пустое
    имя — как есть."""
    if not (owner or "").strip():
        return text
    out: list[str] = []
    inside = False
    for line in text.split("\n"):
        if is_section_heading(line):
            inside = True
            out.append(line)
            continue
        if inside and ((_OTHER_SECTION.match(line)
                        or (_BARE_HEADING.match(line) and _KNOWN_BARE_SECTION.match(line)))
                       and not _BULLET.match(line)):
            inside = False
        if inside and _ASSIGNEE_LINE.match(line):
            line = canon_owner_item(line, owner)
        out.append(line)
    return "\n".join(out)


# Части поручения «**Имя** — дело — срок»: разделитель — тире любого начертания
# или дефис в пробелах, как их пишет модель («–», «-» — DS I3, Sonnet I1 out1).
# Делится только тело после маркера и ящика: дефис маркера списка — не разделитель.
_ITEM_HEAD = re.compile(r"^\s*(?:" + task_line.MARKER + r"\s*)?" + task_line.BOX + r"\s*")
_ITEM_SEP = re.compile(r"(\s+[—–-]\s+)")
_PIECES_TAIL = re.compile(r"\s*\((?:куски|кусок)[^)]*\)\s*$")


def check_deadline_item(line: str, speech: str, day: datetime.date | None, lang: str = "ru") -> str:
    """Один пункт с ящиком: за сроком, который речь не подтверждает, — пометка
    `task_line.DUE_UNHEARD_MARKS` тем же разделителем; срок не стирается
    («— до 28.11 — срок не из речи»): ошибка гейта стоит лишней пометки, а не
    потерянного верного срока (решение 27.10, №805 out3–out5: 8 из 8 Critical —
    стирание верного срока). Срок — часть после имени и дела («**Имя** — дело
    — срок — приписка», с третьей части), которая сроком начинается
    (`fact_check.looks_like_due`).
    Имя и дело гейт не читает: дата внутри дела («сдать отчёт до 28.11») и
    строка «дело — срок» без имени не судятся — разбор срока строки, общий с
    чипом приложения, — №607 (№805 out3: вырезание даты из дела стирало версию
    «до 3.10», а на 555 пунктах стенда чип рисует дату одному). Не трогает:
    пункт с решённым статусом (`task_line.settled`), с полями хвоста или
    пометкой контроля (их ставит человек и контроль), пустой срок («срок не
    указан»), уже помеченный срок (за ним пометка) и срок, подтверждённый речью
    (`fact_check.due_heard`)."""
    rec = task_line.parse(line)
    if rec is None or task_line.settled(line) or rec.fields or rec.control:
        return line
    head = _ITEM_HEAD.match(line)
    if head is None:
        return line
    return _mark_unheard(line, head.end(), speech, day, lang)


def _mark_unheard(line: str, head_end: int, speech: str, day: datetime.date | None, lang: str) -> str:
    """Разметка частей пункта после головы (маркер и ящик кончаются на
    `head_end`): одна на минутки и разбор — части, хвост «(куски …)» и
    пометка у обоих одни (№829, DS C1 in1)."""
    body = line.rstrip()[head_end:]
    trail = line[len(line.rstrip()):]
    pieces = _PIECES_TAIL.search(body)
    body, suffix = (body[:pieces.start()], pieces.group()) if pieces else (body, "")
    parts = _ITEM_SEP.split(body)            # [часть, разделитель, часть, …]
    marks = set(task_line.DUE_UNHEARD_MARKS.values())
    mark = task_line.DUE_UNHEARD_MARKS.get(lang, task_line.DUE_UNHEARD_MARKS["ru"])
    changed = False
    for i in range(4, len(parts), 2):        # 0 — имя, 2 — дело
        piece = parts[i].strip()
        if piece in marks or not fact_check.looks_like_due(piece):
            continue
        if i + 2 < len(parts) and parts[i + 2].strip() in marks:
            continue                         # уже помечен — повторный проход те же байты
        if not fact_check.due_heard(piece, speech, day=day):
            parts[i], changed = parts[i] + parts[i - 1] + mark, True
    if not changed:
        return line
    return line[:head_end] + "".join(parts) + suffix + trail


def check_deadlines(text: str, speech: str, day: datetime.date | None, lang: str = "ru") -> str:
    """Срок поручения, которого нет в речи, — с пометкой «срок не из речи» (№805:
    на длинных встречах модель додумывает 4 срока из 11, а срок в окне «Задачи»
    читается как факт). Обходит каждый пункт с ящиком во всём документе, а не
    только раздел поручений: окно «Задачи» берёт любой «- [ ]» минуток, и срок
    под чужим заголовком тоже рисуется чипом (Haiku I3 out1). `day` — день
    встречи для дат без месяца («к 28-му»); None — такие даты речью не
    подтверждены."""
    if not speech.strip():
        return text
    return "\n".join(check_deadline_item(line, speech, day, lang=lang) for line in text.split("\n"))


# Разбор после встречи (№829): пункты «- **Кто** — что — срок» без ящика в
# разделе «## Задачи». Голова пункта — те же маркер и ящик грамматики строки
# поручения: пункт списка (`_BULLET`, маркер и пробел — иначе «*» маркера съел бы
# жирное «**Имя**» строки без маркера), ящик необязателен. Своя регулярка
# «имени» была бы третьей грамматикой пункта (DS C1 in1, маркер «1.»).
_LIST_HEAD = re.compile(_BULLET.pattern + r"(?:" + task_line.BOX + r"\s*)?")
_HEADING = re.compile(r"^(#{1,6})\s")
# Заголовок раздела задач оба промпта разбора задают одинаково — «## Задачи»
# (509 из 510 разборов владельца 29.10, ни одного подзаголовка внутри); хвост
# после слова («## Задачи (кто/что/срок)») раздел не отменяет (DS I3 in1),
# регистр — тоже (Sonnet M1 out1). Единственное число раздел не открывает:
# «### Задача для …» внутри «Рекомендаций» судился бы (Haiku M1 out2).
_DEBRIEF_TASKS = re.compile(r"^(#{1,6})\s+Задачи(?![^\W\d_])", re.IGNORECASE)


def check_debrief_deadlines(text: str, speech: str, day: datetime.date | None) -> str:
    """Гейт срока №805 на разделе «Задачи» разбора: за сроком, которого речь не
    подтверждает, — «— срок не из речи», срок не стирается. Разбор не канон
    задач (вкладка его не читает), его читает человек: до №829 «сегодня
    (05.10)» у встречи 06.10 и «до конца дня 27.10» у встречи 28.10 стояли
    фактами (замер октября: 19 сроков из 159 речь не подтверждает).

    Раздел — от заголовка «Задачи» до заголовка того же или более высокого
    уровня (Sonnet I2 in1): подзаголовок внутри раздела его не закрывает, и
    вложенный «Задачи» уровень открытого раздела не меняет (DS I2 out1).
    Прочие разделы разбора не судятся: в «Рекомендациях» сроки — предложения
    модели по построению. Пункт с ящиком судится по тем же правилам, что в
    минутках (`check_deadline_item`), без ящика — как пункт с открытым ящиком;
    пункт с полями хвоста или пометкой контроля не трогается, как в минутках:
    дата поля («📅 2026-11-05» даёт «11.05») и тире внутри пометки контроля
    пошли бы в суд срока (DS C1, Haiku I1 out2; в разборах таких строк 0 из
    2494). Язык пометки — русский: промпты разбора русские."""
    if not speech.strip():
        return text
    out: list[str] = []
    level = 0                                # уровень заголовка «Задачи»; 0 — вне раздела
    for line in text.split("\n"):
        heading = _HEADING.match(line)
        if heading:
            if len(heading.group(1)) <= level:
                level = 0
            tasks = _DEBRIEF_TASKS.match(line)
            if tasks and not level:
                level = len(tasks.group(1))
        elif level:
            line = _check_debrief_item(line, speech, day)
        out.append(line)
    return "\n".join(out)


def _check_debrief_item(line: str, speech: str, day: datetime.date | None) -> str:
    head = _LIST_HEAD.match(line)
    if (head is None or task_line.settled(line) or task_line.fields(line)
            or task_line.CONTROL_MARK.search(line)):
        return line
    return _mark_unheard(line, head.end(), speech, day, "ru")
