"""Шов способности: чем граф считает векторы, не зная, кто их считает.

Графовый слой держит индекс и решает, что на что похоже; слой моделей знает
Ollama, имена моделей и таймауты. Между ними — значение, а не импорт: поиск
получает готовый векторизатор параметром и не может спросить, откуда тот взялся.

Почему пара, а не две вещи рядом. Имя модели — не украшение вызова: под ним
подписан дисковый кэш векторов (`GraphSearch.cache_key`). Пока функция и имя
ехали двумя независимыми параметрами, можно было передать функцию одной модели
и имя другой: векторы чужого пространства легли бы под привычным именем, и
косинус запроса против такого кэша — шум, а не свидетельство. Одним значением
расхождение нечем выразить.

Модуль лежит в нижнем слое сознательно. Тип нужен обоим берегам — и тому, кто
способность строит, и тому, кто её получает, — а значит не может жить ни у
одного из них: импорт ради аннотации восстановил бы ровно то ребро, которое
шов и снимает (гейт раскладки считает импорты обходом всего дерева, включая
`if TYPE_CHECKING`). Зависимостей у модуля нет и быть не должно: его читает и
`scripts/doctor.py`, который обязан печатать рецепт на машине, где ещё нечем
ходить в сеть.
"""
from __future__ import annotations

import dataclasses
from typing import Callable

#: Модель эмбеддингов по умолчанию. Не страховка, а боевое значение: ключа
#: `sufler.embed_model` нет ни в одном конфиге поставки, поэтому именно эта
#: строка подписывает дисковые кэши всех установок. Менять её — переиндексация
#: графа у каждого, у кого он уже собран.
DEFAULT_EMBED_MODEL = "bge-m3:latest"

#: Имя пустого векторизатора. Своё, не боевое: под именем подписаны и кэш на
#: диске, и индекс в процессе, так что «моделей нет» обязано отличаться от
#: «bge-m3» — иначе первый позвавший без конфига застолбит индекс графа, а
#: пришедший следом с настоящим конфигом молча получит его (круг 1 по коду,
#: DS I2). Скобки в имени делают его непохожим на модель Ollama намеренно.
NO_MODEL = "(моделей нет)"


#: Пороги, замеренные на bge-m3 — боевые значения всех установок. Каждый был
#: подобран по разбросу косинусов именно этой модели (дежавю — замер 22.07,
#: 0.33…0.45 на живом графе; ревизия ядер и поиск — свои замеры), поэтому у
#: другой модели они не значат ничего: у неё свой разброс. Ключи — имена в
#: `sufler.embed_thresholds`, через который владелец задаёт пороги своей модели
#: (их считает `scripts/embed_bench.py`).
BGE_M3_THRESHOLDS = {
    "tier3_prefilter": 0.55,    # ревизия ядер: ниже — пару даже не судим NLI
    "search_sim_floor": 0.35,   # поиск: ниже — семантический шум
    "search_low_sim": 0.47,     # поиск: гейт честности «⚠» (вместе с покрытием)
    "deja_vu_margin": 0.04,     # дежавю: отрыв лидера от медианы ядер
}
THRESHOLD_KEYS = tuple(BGE_M3_THRESHOLDS)


@dataclasses.dataclass(frozen=True)
class EmbedProfile:
    """Что надо знать о модели эмбеддингов, кроме её имени.

    Две вещи, и обе — свойство модели, а не потребителя:

    * **Префиксы задачи.** bge-m3 считает вектор по голому тексту. Семейство
      EmbeddingGemma обучено с инструкцией в начале входа — запрос и документ
      размечаются по-разному (`config_sentence_transformers.json` модели), и без
      разметки вектор хуже, а косинусы сдвинуты. Ollama префиксов сама не
      ставит: их ставит тот, кто знает, что именно он векторизует.
    * **Пороги.** Абсолютные числа, подобранные по разбросу одной модели. Чужой
      модели они достаются как «неоткалиброванные»: контуры работают, но
      `calibrated` ложно, и владелец слышит об этом строкой.

    Профиль едет внутри `Embedder` вместе с именем: префиксы меняют векторы,
    значит, подписывают кэш так же, как имя (`cache_tag`).
    """

    family: str = ""
    query_prefix: str = ""
    document_prefix: str = ""
    pair_prefix: str = ""
    tier3_prefilter: float = BGE_M3_THRESHOLDS["tier3_prefilter"]
    search_sim_floor: float = BGE_M3_THRESHOLDS["search_sim_floor"]
    search_low_sim: float = BGE_M3_THRESHOLDS["search_low_sim"]
    deja_vu_margin: float = BGE_M3_THRESHOLDS["deja_vu_margin"]
    calibrated: bool = True

    def query(self, text: str) -> str:
        """Текст как поисковый запрос: реплика встречи, вопрос к памяти."""
        return self.query_prefix + text

    def document(self, text: str) -> str:
        """Текст как документ, среди которого ищут: ядро, блок файла графа."""
        return self.document_prefix + text

    def pair(self, text: str) -> str:
        """Текст одной из двух равноправных сторон пары — ревизия ядер."""
        return self.pair_prefix + text

    def cache_tag(self) -> str:
        """Подпись префиксов для ключа кэша; без префиксов — пусто.

        Пусто — намеренно: у bge-m3 префиксов нет, и ключ кэша поиска у всех
        установок остаётся прежним — переиндексации нет. У модели с префиксами
        другой префикс — другие векторы, значит, и другой ключ.
        """
        if not (self.query_prefix or self.document_prefix or self.pair_prefix):
            return ""
        return f"doc={self.document_prefix!r}"


#: Префиксы семейства EmbeddingGemma (1 и 2) — из `prompts` модели:
#: SearchQuery/Retrieval-query, Document/Retrieval-document, STS.
_GEMMA_PREFIXES = {
    "query_prefix": "task: search result | query: ",
    "document_prefix": "title: none | text: ",
    "pair_prefix": "task: sentence similarity | query: ",
}


def embed_profile(model: str, overrides: dict | None = None) -> EmbedProfile:
    """Профиль модели по имени Ollama плюс пороги владельца.

    `overrides` — `sufler.embed_thresholds`: только известные ключи
    `THRESHOLD_KEYS` с числом; остальное отбрасывается (опечатка в ключе не
    должна молча ставить порог в ноль). Заданный владельцем порог считается
    откалиброванным — за него отвечает тот, кто его замерил; профиль
    неоткалиброван, пока хоть один порог взят у bge-m3 для чужой модели.
    """
    base = str(model or "").lower()
    if base.startswith("bge-m3"):
        kw: dict = {"family": "bge-m3"}
        own = True
    elif "embeddinggemma" in base:
        kw = {"family": "embeddinggemma", **_GEMMA_PREFIXES}
        own = False
    else:
        kw = {"family": ""}
        own = False
    given = {}
    for key, value in (overrides or {}).items():
        if key not in THRESHOLD_KEYS or isinstance(value, bool):
            continue
        try:
            number = float(value)
        except (TypeError, ValueError):
            continue
        if number == number and -1.0 <= number <= 1.0:     # не NaN, косинус
            given[key] = number
    kw.update(given)
    kw["calibrated"] = own or set(given) == set(THRESHOLD_KEYS)
    return EmbedProfile(**kw)


def embed_model_name(cfg: dict, model: str | None = None) -> str:
    """Чем считаем векторы: явное имя, конфиг владельца или дефолт поставки.

    Единственный резолвер на проект — и живёт он здесь, а не рядом с
    транспортом, потому что имя спрашивают оба берега и диагностика. У доктора
    выбора нет вовсе: слой моделей тянет `requests`, а доктор обязан печатать
    рецепт на машине, где ставить пакеты ещё нечем.

    Раньше эта строчка жила в трёх местах — слой моделей, ключ дискового кэша
    поиска, контур дежавю, — и каждая копия была отдельной возможностью
    разойтись. Имя подписывает кэш векторов: расхождение стоит не ошибки, а
    часов пересчёта у каждого владельца.
    """
    return str(model or (cfg.get("sufler") or {}).get("embed_model") or DEFAULT_EMBED_MODEL)


class SeamTransportError(OSError):
    """Способность не сработала по причине, которая потребителя не касается.

    Сеть, занятый сервер, запрещённый политикой адрес — для графа это один
    исход: векторов нет, идём лексикой. Раньше потребитель перечислял типы
    исключений чужого слоя и обязан был угадать их таксономию; угадал не всё —
    `RuntimeError` от политики адреса летел мимо и превращался в «память ещё
    прогревается» навсегда (круг 1 по коду, обе головы).

    Теперь перечисляет поставщик, у которого это знание и есть, а граф ловит
    один объявленный класс. Наследование от `OSError` — чтобы потребитель,
    ловящий транспорт по-старому, не сломался.

    `policy` отделяет «нельзя по настройке владельца» от «сервер не ответил»:
    для контура это один исход, а для человека — разные слова. Называть отказ
    его собственной настройки «модель занята» значит отправить его чинить не
    то (круг 2 по коду, DS I3).
    """

    def __init__(self, message: str, *, policy: bool = False) -> None:
        super().__init__(message)
        self.policy = policy


@dataclasses.dataclass(frozen=True)
class Judge:
    """Судья пары тезисов: готовность и суд одним значением.

    Две фазы, и они охраняют разные ресурсы — схлопывать их нельзя:

    * `refused` — дешёвая фаза, посчитанная при сборке: файлы модели на диске,
      пакеты импортируются. Пустая строка значит «можно пробовать». Её
      спрашивают ДО чтения ядер и эмбеддингов: на установке без NLI-модели
      (слой опционален, модель кладут руками) ревизия иначе прочитала бы весь
      корпус ядер и разбудила эмбеддер впустую после каждой встречи.
    * `ready()` — дорогая: поднимает ONNX-сессию и проверяет её живой парой.
      Стоит ПОСЛЕ эмбеддингов, потому что охраняет объявление «прогон
      состоялся»: при битой модели суд молча не находит ничего, а отметка
      инкремента уезжает вперёд, и свежие ядра выпадают из фокуса навсегда.

    `entail(premise, hypothesis)` отдаёт вероятность следования. Если судить
    нечем — бросает `SeamTransportError`, а не возвращает ноль: ноль
    неотличим от честного «не следует», и на этом неразличении построен
    дефект, который дважды стоил нам инкремента. Пара, на которой судья
    отказал, обязана вернуться в фокус следующего прогона.
    """

    ready: Callable[[], bool] = dataclasses.field(repr=False)
    entail: Callable[[str, str], float] = dataclasses.field(repr=False)
    refused: str = ""


@dataclasses.dataclass(frozen=True)
class Embedder:
    """Векторизатор и имя, под которым он считает.

    `run(texts, timeout)` отдаёт по вектору на текст. Контракт исходов узкий,
    и потребитель на него полагается:

    * векторы — всё хорошо;
    * пустой список — сервер ответил, но векторов не дал (модели нет, занят);
    * `SeamTransportError` — не сработало по своей причине: сеть, занятый
      сервер, запрещённый политикой адрес. Потребитель гасит это в лексику:
      подсказка на встрече важнее семантики.

    Всё остальное (`TypeError`, `AttributeError`) — ошибка проводки, а не
    деградация, и обязано долетать до человека. Ловить их «на всякий случай»
    значит неделями отдавать подсказки без семантики, ни разу не крикнув.

    Пару собирает дверь векторов пакета: пользователь пакета — фабрикой
    `charoite_graph.embed_door.ollama_embedder` (адрес под политикой пакета),
    адаптер слоя моделей приложения `llm.embedder` — самой дверью `embedder`: он
    один знает, как резолвится имя и откуда берётся адрес.
    Собранная руками пара законна в тестах, где обе половины пишет один человек
    в одной строке. Имя подписывает кэш векторов — одно имя на одно пространство.
    """

    run: Callable[[list[str], float], list[list[float]]] = dataclasses.field(repr=False)
    model: str

    def __post_init__(self) -> None:
        """Векторизатор без имени — ошибка вызывающего, а не пустая подпись.

        Имя подписывает дисковый кэш векторов: пустая строка легла бы под
        индекс графа, и чужое пространство косинуса выдавало бы себя за
        своё. Пустая строка неотличима от «имя забыли» — а это ошибка
        проводки, обязанная долететь до человека.
        """
        if not self.model:
            raise ValueError("векторизатор без имени: подписывать кэш нечем")
        if self.profile is None:
            # Профиль — свойство модели: собранный без него векторизатор получает
            # профиль по имени, а не «пустой» — иначе EmbeddingGemma, собранная
            # руками, считала бы векторы без префиксов под своим же именем.
            object.__setattr__(self, "profile", embed_profile(self.model))
    #: Почему способности не будет, если это известно уже при сборке. Пустая
    #: строка — всё в порядке. Отказ политики адреса виден фабрике сразу, а
    #: потребитель узнал бы о нём только с первым вектором — которого на
    #: пустом кэше не бывает вовсе, и владельцу называлась чужая причина
    #: («сервер занят» вместо «вы запретили этот адрес»). Исход принадлежит
    #: способности, а не тому, кто её звал (круг 3 по коду, обе головы).
    refused: str = ""
    #: Префиксы и пороги модели (`EmbedProfile`). Не задан — берётся по имени.
    #: В сравнении и repr не участвует: два векторизатора одной модели с разными
    #: порогами считают одни и те же векторы.
    profile: EmbedProfile | None = dataclasses.field(default=None, compare=False, repr=False)
