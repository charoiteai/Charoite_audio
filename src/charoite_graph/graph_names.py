"""Имена узлов графа: безопасное имя, ключ сравнения, метки диаризации.

Вынесено из graph_updater (аудит памяти 07.09): эти функции нужны демону
(graph_nodes — индекс узлов для живых подсказок), линту (graph_doctor) и
уборке ссылок (graph_links), а graph_updater тянет за собой requests, llm и
cloud — импортировать его ради трёх регулярных выражений дорого и в демоне,
и в тестах. Реализация не менялась; graph_updater реэкспортирует те же имена.
"""
from __future__ import annotations

import re


def safe_name(name: str) -> str:
    """Имя узла графа: безопасное и для файловой системы, и для вики-ссылок.

    Раньше вырезались только запрещённые в именах файлов символы, а из имени
    строится `[[Папка/Имя|Имя]]`. Сущность «Витрина [v2]» давала ссылку,
    которую Obsidian закрывал на первом `]]` — узел оставался несвязанным;
    `#` уводил ссылку на заголовок, `^` — на блок. Отдельно: имя, схлопнутое
    в пустоту, давало скрытый файл «.md» и ломало поиск канонического узла
    (пустая строка входит в любую).
    """
    s = re.sub(r'[/\\:*?"<>|\[\]#^]', "-", name)
    s = re.sub(r"\s+", " ", s).strip(" .-")[:60]
    return s or "без имени"


_PLACEHOLDER_RE = re.compile(
    r"^(?:собеседник|участник|спикер|speaker|participant|发言人|参会者)(?: ?[\d一二三四五六七八九十]+)?$")
_LABEL_TAIL_RE = re.compile(r"\s*[(（]([^()（）]*)[)）]\s*$")


def name_key(name: str) -> str:
    """Ключ сравнения имён узлов: регистр, пунктуация, скобки, дефис и
    подчёркивание людей не различают — «Иван (Иванов)» и «Иван Иванов»,
    «ИИ-агент» и «ИИ_агент», «Реестр 385 130» и «Реестр 385-130» жили в графе
    четырьмя парами узлов (аудит 28.08)."""
    return " ".join(re.sub(r"[\W_]+", " ", name, flags=re.UNICODE).casefold().split())


def bag_key(name: str) -> str:
    """Ключ без порядка слов: «Иван Петров» и «Петров Иван» — один человек.

    Модель отдаёт имя то в порядке «имя фамилия», то «фамилия имя», а узел
    заведён в одном из них: 107 ссылок на «Имя Фамилия» при живом узле
    «Фамилия Имя» (замер 07.09). Однословные имена ключ не меняет."""
    return " ".join(sorted(name_key(name).split()))


def is_speaker_placeholder(name: str) -> bool:
    """«Собеседник 3», «Speaker 2» — метка диаризации, а не человек.

    Узел на такую метку склеивал разных людей из разных встреч в одного:
    «Собеседник 3» встречи А и «Собеседник 3» встречи Б — один файл в Люди
    с сотней входящих ссылок (аудит графа 28.08: 17 таких узлов, у трёх по
    135–141 ссылки). Метка живёт в заметке встречи текстом и подписывает
    цитаты из стенограммы; узла и ссылки на него не получает.
    """
    # По ключу имени: «Собеседник-3», «Собеседник №3», «Собеседник 3,» и
    # «Собеседник 3 (муж)» — та же метка; иначе она вливалась через name_key
    # в старый узел-склейщик (DS, круг-1 по #448 I4).
    bare = re.sub(r"\s*[(（].*?[)）]\s*$", "", safe_name(name))
    return bool(_PLACEHOLDER_RE.match(name_key(re.sub(r"[№#]", " ", bare))))


def is_placeholder_node(stem: str) -> bool:
    """Узел в Люди — метка диаризации? «Собеседник 3», «Speaker 2 (муж)»,
    «Собеседник 1 (Саша)» — да: облако дописывало имя в скобках, но узел
    остаётся склейкой разных людей. Одно правило для doctor и миграции."""
    bare = re.sub(r"\s*[(（].*?[)）]\s*$", "", stem)
    if is_speaker_placeholder(bare):
        return True
    m = re.search(r"[(（]([^()（）]*)[)）]\s*$", stem)
    return bool(m) and is_speaker_placeholder(m.group(1))   # один набор меток, что и для целого имени (luna I5)


#: Метка диаризации деятелем в тексте: «Собеседник 3 предложил…», «[[Собеседник 3]]».
#: В скобке после имени («Вера (Собеседник 4)») — пометка, а не деятель.
_SPEAKER_IN_TEXT_RE = re.compile(r"(?<![(（\w])(?:собеседник|спикер|speaker)\s*№?\s*\d+", re.IGNORECASE)


def has_speaker_actor(text: str) -> bool:
    """Есть ли в тексте (досье, ядро) метка диаризации деятелем: за меткой нет
    человека, и факты разных людей разных встреч сходятся на «Собеседнике 3»
    (№611, замер 26.10: 169 досье из 1013)."""
    return _SPEAKER_IN_TEXT_RE.search(text or "") is not None


def bare_name(name: str) -> str:
    """Имя без хвостовой скобки: «Саша (из минуток)» → «Саша». Скобка — пометка
    модели или ревизии, а не часть имени: тёзок ищут по имени без неё."""
    return re.sub(r"\s*[(（][^()（）]*[)）]\s*$", "", name).strip() or name


def namesake_index(names) -> dict[str, list[str]]:
    """Слово имени (ключом `name_key`) → многословные имена с этим словом.

    Порядок слов не важен: «Саша Образцов» и «Образцов Саша» оба лягут под «саша».
    Метки диаризации в индекс не идут — за ними нет человека."""
    index: dict[str, list[str]] = {}
    for name in names:
        words = name_key(bare_name(name)).split()
        if len(words) < 2 or is_speaker_placeholder(bare_name(name)):
            continue
        for w in dict.fromkeys(words):
            index.setdefault(w, []).append(name)
    return index


def bare_namesakes(name: str, index: dict[str, list[str]]) -> list[str]:
    """Голое имя с тёзками: однословное имя («Саша»), у которого среди живых узлов
    есть многословные с тем же словом («Саша Образцов», «Саша Сидоров») — их список,
    иначе пусто.

    Под голым именем граф копит факты разных людей: каждый «Саша» встречи садится
    в один узел (№611, замер 26.10: 36 таких узлов, 1553 ссылки). Один предикат на
    всех — доктор считает по нему, затвор на входе (№611 этап 2) решает по нему же."""
    words = name_key(bare_name(name)).split()
    if len(words) != 1 or is_speaker_placeholder(bare_name(name)):
        return []
    return sorted(index.get(words[0], []))


def strip_speaker_label(name: str) -> str:
    """«Саша (Спикер 1)» → «Саша»: метка диаризации в скобках у настоящего
    имени — пометка модели, не часть имени.

    Фильтр `is_speaker_placeholder` снимает только хвостовую скобку и судит
    остаток: «Саша (Спикер 1)» проходил как человек «Саша (Спикер 1)» и
    получал узел-склейщик с меткой в имени (GLM, аудит памяти 07.09) — ровно
    те четыре узла, что doctor показывал после миграции №125. Имя-метка
    целиком («Собеседник 2 (Саша)») не трогается: его отсеет
    `is_speaker_placeholder`, а человек в скобках — догадка облака, не факт."""
    m = _LABEL_TAIL_RE.search(name or "")
    if not m or not is_speaker_placeholder(m.group(1)):
        return name
    bare = name[:m.start()].strip()
    return bare if bare and not is_speaker_placeholder(bare) else name
