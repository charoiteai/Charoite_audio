"""Имена узлов графа: безопасное имя, ключ сравнения, метки диаризации.

Вынесено из graph_updater (аудит памяти 07.09): эти функции нужны демону
(graph_nodes — индекс узлов для живых подсказок), линту (graph_doctor) и
уборке ссылок (graph_links), а graph_updater тянет за собой requests, llm и
cloud — импортировать его ради трёх регулярных выражений дорого и в демоне,
и в тестах. Реализация не менялась; graph_updater реэкспортирует те же имена.
"""
from __future__ import annotations

import re


def safe_name(name: str) -> str:
    """Имя узла графа: безопасное и для файловой системы, и для вики-ссылок.

    Раньше вырезались только запрещённые в именах файлов символы, а из имени
    строится `[[Папка/Имя|Имя]]`. Сущность «Витрина [v2]» давала ссылку,
    которую Obsidian закрывал на первом `]]` — узел оставался несвязанным;
    `#` уводил ссылку на заголовок, `^` — на блок. Отдельно: имя, схлопнутое
    в пустоту, давало скрытый файл «.md» и ломало поиск канонического узла
    (пустая строка входит в любую).
    """
    s = re.sub(r'[/\\:*?"<>|\[\]#^]', "-", name)
    s = re.sub(r"\s+", " ", s).strip(" .-")[:60]
    return s or "без имени"


#: Слова меток диаризации — одни на метку-имя узла и метку-деятеля в тексте:
#: два набора разъехались бы на первой правке (n611-s1-out1 DS I3).
_SPEAKER_WORDS = ("собеседник", "участник", "спикер", "speaker", "participant", "发言人", "参会者")
_PLACEHOLDER_RE = re.compile(
    r"^(?:" + "|".join(_SPEAKER_WORDS) + r")(?: ?[\d一二三四五六七八九十]+)?$")
_LABEL_TAIL_RE = re.compile(r"\s*[(（]([^()（）]*)[)）]\s*$")


def name_key(name: str) -> str:
    """Ключ сравнения имён узлов: регистр, пунктуация, скобки, дефис и
    подчёркивание людей не различают — «Иван (Иванов)» и «Иван Иванов»,
    «ИИ-агент» и «ИИ_агент», «Реестр 385 130» и «Реестр 385-130» жили в графе
    четырьмя парами узлов (аудит 28.08)."""
    return " ".join(re.sub(r"[\W_]+", " ", name, flags=re.UNICODE).casefold().split())


def bag_key(name: str) -> str:
    """Ключ без порядка слов: «Иван Петров» и «Петров Иван» — один человек.

    Модель отдаёт имя то в порядке «имя фамилия», то «фамилия имя», а узел
    заведён в одном из них: 107 ссылок на «Имя Фамилия» при живом узле
    «Фамилия Имя» (замер 07.09). Однословные имена ключ не меняет."""
    return " ".join(sorted(name_key(name).split()))


def is_speaker_placeholder(name: str) -> bool:
    """«Собеседник 3», «Speaker 2» — метка диаризации, а не человек.

    Узел на такую метку склеивал разных людей из разных встреч в одного:
    «Собеседник 3» встречи А и «Собеседник 3» встречи Б — один файл в Люди
    с сотней входящих ссылок (аудит графа 28.08: 17 таких узлов, у трёх по
    135–141 ссылки). Метка живёт в заметке встречи текстом и подписывает
    цитаты из стенограммы; узла и ссылки на него не получает.
    """
    # По ключу имени: «Собеседник-3», «Собеседник №3», «Собеседник 3,» и
    # «Собеседник 3 (муж)» — та же метка; иначе она вливалась через name_key
    # в старый узел-склейщик (DS, круг-1 по #448 I4).
    bare = re.sub(r"\s*[(（].*?[)）]\s*$", "", safe_name(name))
    return bool(_PLACEHOLDER_RE.match(name_key(re.sub(r"[№#]", " ", bare))))


def is_label_tag(inner: str) -> bool:
    """Содержимое скобки — метка диаризации, в том числе с пометкой через запятую:
    «Собеседник 1», «Собеседник 1, муж». Одно правило для писателя
    (`strip_speaker_label`), доктора и миграции (n611-s1-out3 DS M1)."""
    return any(is_speaker_placeholder(part) for part in (inner or "").split(","))


def is_placeholder_node(stem: str) -> bool:
    """Узел в Люди — метка диаризации? «Собеседник 3», «Speaker 2 (муж)»,
    «Собеседник 1 (Саша)» — да: облако дописывало имя в скобках, но узел
    остаётся склейкой разных людей. Одно правило для doctor и миграции."""
    bare = re.sub(r"\s*[(（].*?[)）]\s*$", "", stem)
    if is_speaker_placeholder(bare):
        return True
    m = re.search(r"[(（]([^()（）]*)[)）]\s*$", stem)
    return bool(m) and is_label_tag(m.group(1))   # один набор меток, что и для целого имени (luna I5)


#: Метка диаризации деятелем в тексте: «Собеседник 3 предложил…», «слова Собеседника 3»,
#: «[[Собеседник 3]]», «Спикер-3», «Собеседник 3/4», «发言人3决定». Число — до трёх цифр
#: целым словом: «спикер 2024 года», «спикер 3D», «участник 14.09», «участник 2-й линии» —
#: не метка (замер 27.10: все 23 совпадения не со словом «собеседник» в досье рабочего
#: графа — даты и «2-й»; дробь «Собеседник 3/4» — в графах 70+ раз, метка). Граница —
#: явным классом, не `\w`: иероглиф вплотную к номеру — следующее слово (n611-s1-out3).
_WORD_CH = r"0-9A-Za-zА-Яа-яЁё_"
_SPEAKER_IN_TEXT_RE = re.compile(
    r"(?<![A-Za-zА-Яа-яЁё])(?:" + "|".join(_SPEAKER_WORDS) + r")(?:а|у|ом|е)?"
    r"[\s\-_№#]*(?:\d{1,3}(?![" + _WORD_CH + r"])(?![.:]\d|-[A-Za-zА-Яа-яЁё])|[一二三四五六七八九十]+)",
    re.IGNORECASE)

#: Закрытая скобка без вложенных в пределах строки — пометка при имени или ремарка:
#: одинокая «(» не склеивается с «1)» маркера списка абзацем ниже (Sonnet I3).
_PAREN_RE = re.compile(r"[(（][^()（）\n]*[)）]")
_MASK = "\0"
#: Вики-ссылка: цель до «|», подпись до «]]»; перенос строки внутри допустим, «[»
#: — нет: незакрытая «[[» не съедает соседнюю ссылку (n815-out1 DS M3).
_WIKI_LINK_RE = re.compile(r"\[\[([^\[\]|]*)(?:\|([^\[\]]*))?\]\]")


def has_speaker_actor(text: str) -> bool:
    """Есть ли в тексте досье метка диаризации деятелем: за меткой нет человека,
    и факты разных людей разных встреч сходятся на «Собеседнике 3» (№611, замер
    27.10: 165 досье). Метка в закрытых скобках («Вера (Собеседник 4)», «(муж,
    Собеседник 4)») — пометка при имени, а не деятель. Скобки вырезаются парами:
    незакрытая «(» выше по тексту («:(», обрезанная ссылка) метку не прячет
    (n611-s1-out2 DS I3)."""
    return bool(_speaker_spans(text or ""))


def _speaker_spans(text: str) -> list[tuple[int, int]]:
    """Где в тексте метки деятелем, смещения — в исходной строке. Один поиск на
    детектор и чистку: две копии разошлись бы на первой правке (n815-in3 Sonnet C1).

    Маска той же длины символом вне класса разделителей метки: пробел давал
    спану тянуться через скобку, и «Собеседник (Вера) 3» терял имя (n815-out1
    Sonnet I2). Закрытые скобки — пометка при имени. Ссылка на узел-метку —
    деятель целиком (спан всей ссылки); у ссылки на живой узел цель — адрес, не
    деятель, маскируется, подпись остаётся текстом (n815-out1 DS I1)."""
    masked = text
    for _ in range(2):                 # «((Собеседник 3))» — вложенная пара
        masked = _PAREN_RE.sub(lambda m: _MASK * len(m.group(0)), masked)
    spans = []

    def link(m: re.Match) -> str:
        if is_placeholder_node(_link_target_stem(text[m.start(1):m.end(1)])):
            spans.append(m.span())
            return _MASK * len(m.group(0))
        return _MASK * (m.end(1) - m.start()) + masked[m.end(1):m.end()]

    masked = _WIKI_LINK_RE.sub(link, masked)
    spans += [m.span() for m in _SPEAKER_IN_TEXT_RE.finditer(masked)]
    return sorted(spans)


#: Метка деятелем → кто она есть: участник встречи. Падеж — по окончанию метки
#: («слова Собеседника 3» → «слова участника встречи»). Слово не метка: за
#: «участник» идёт «встречи», а не номер, — повторная чистка ничего не меняет.
UNLABELED = "участник встречи"
_UNLABELED_CASES = {"": UNLABELED, "а": "участника встречи", "у": "участнику встречи",
                    "ом": "участником встречи", "е": "участнике встречи"}
#: Правило для модели — одно на сборку и ревизию: ревизор, не знавший его, видел в
#: двух «участниках встречи» одного человека и метил ложное противоречие (n815-out1 I2).
UNLABELED_RULE = ("«Участник встречи» — голос без имени, свой на каждой встрече: не человек. "
                  "В «Кто в теме» его не ставить; слова двух «участников встречи» — не противоречие "
                  "и не смена позиции одного человека.")
_LABEL_CASE_RE = re.compile(r"(?:" + "|".join(_SPEAKER_WORDS) + r")(а|у|ом|е)?", re.IGNORECASE)
_LABEL_TAIL_NUM_RE = re.compile(r"(?:[/\-–]\d{1,3})*")      # «Собеседник 3/4», «Собеседник 3-4»
_SENTENCE_START_RE = re.compile(r"(?:\n|[.!?…»]\s)[\s\-*>#\d.)\[\]«\"_:]*\Z")
_SENTENCE_LOOKBACK = 40


def _link_target_stem(target: str) -> str:
    """Цель ссылки как имя узла: последний сегмент без якоря и `.md` (как `dossier.scan`)."""
    return re.split(r"[#^]", target)[0].split("/")[-1].strip().removesuffix(".md").strip()


def unlabel_speakers(text: str) -> str:
    """Текст для модели и тело досье без меток деятелем: «Собеседник 3» — номер
    голоса одной встречи, а не человек; в досье по многим встречам он сводил
    факты разных людей в одного (№815). Метка → «участник встречи»; ссылка на
    узел-метку → её подпись, без подписи — то же слово (цель не переписывается:
    битая ссылка хуже текста); ссылка на живой узел остаётся ссылкой. Метка в закрытых
    скобках при имени остаётся. Цена: два голоса одной встречи становятся одним
    «участником встречи» — сознательно, номер между встречами ничего не значит.

    Только в памяти — файлы графа не переписывает. Контракт (тесты):
    `not has_speaker_actor(unlabel_speakers(x))` и повтор ничего не меняет.
    """
    text = text or ""
    out, pos = [], 0
    for a, b in _speaker_spans(text):
        if a < pos:                    # хвост «/4» прошлой метки
            continue
        lm = _WIKI_LINK_RE.match(text, a) if text.startswith("[[", a) else None
        if lm and (lm.group(2) or "").strip():
            out += [text[pos:a], unlabel_speakers(lm.group(2).strip())]
            pos = b
            continue
        if lm:
            word = UNLABELED
        else:
            b = _LABEL_TAIL_NUM_RE.match(text, b).end()
            word = _UNLABELED_CASES[(_LABEL_CASE_RE.match(text, a).group(1) or "").lower()]
        # заглавная — только в начале предложения или строки: «с Собеседником 3» → «с участником»
        before = ("\n" if a <= _SENTENCE_LOOKBACK else "") + text[max(0, a - _SENTENCE_LOOKBACK):a]
        if (lm or text[a].isupper()) and _SENTENCE_START_RE.search(before):
            word = word[0].upper() + word[1:]
        out += [text[pos:a], word]
        pos = b
    return "".join(out) + text[pos:]


def _is_tag(inner: str, tags: frozenset[str]) -> bool:
    """Хвостовая скобка у имени — пометка, а не часть имени? Да, если в ней метка
    диаризации («(Собеседник 1, муж)»), строчное слово («(аналитик)»), перечень
    через запятую, аббревиатура заглавными («(ОТДЕЛ)») или имя узла Систем и Команд
    из `tags` («(Витрина)»). Иначе слово с заглавной — часть имени («Иван (Иванов)»;
    замер 27.10 на рабочем графе: из 16 скобок с заглавной 3 фамилии, 5 имён и
    уменьшительных, 2 аббревиатуры систем, 4 метки, 1 перечень, 1 отчество)."""
    inner = inner.strip()
    return (not inner or inner[:1].islower() or "," in inner or _is_place_tag(inner, tags)
            or bool(_LABEL_WORD_RE.search(inner)))


#: Слово метки целым словом: «(Спикер 41)», но не фамилия «(Собеседников)» или
#: «(СпикерСофт)» (n611-s1-out3 Sonnet M2, DS I3).
_LABEL_WORD_RE = re.compile(r"(?<![A-Za-zА-Яа-яЁё])(?:" + "|".join(_SPEAKER_WORDS) + r")(?:а|у|ом|е)?"
                            r"(?![A-Za-zА-Яа-яЁё])", re.IGNORECASE)


def _is_place_tag(inner: str, tags: frozenset[str]) -> bool:
    """Скобка называет место человека — аббревиатуру заглавными или узел Систем и
    Команд: «Илья (ОТДЕЛ)». Такая пометка различает тёзок сама, узел не голый."""
    inner = inner.strip()
    return inner.isupper() or inner.casefold().replace("ё", "е") in tags


def name_words(name: str, tags: frozenset[str] = frozenset()) -> list[str]:
    """Слова имени человека для тёзок: «Саша (из минуток)» → [«саша»], «Дмитрий
    (Фамилия)» → [«дмитрий», «фамилия»], «Жан-Пьер» → [«жан-пьер»].

    Хвостовая скобка-пометка (`_is_tag`) снимается; `tags` — имена узлов Систем и
    Команд графа в нижнем регистре, «ё» = «е»: «Иван (Витрина)» — Иван из Витрины,
    а не тёзка «витрина» (n611-s1-out2 Sonnet I3). Дефис имя не режет — «Жан-Пьер»
    один человек (Haiku I1); «ё» = «е»; число — не слово: копия «Саша 2» не полный
    тёзка (Sonnet I3)."""
    m = _LABEL_TAIL_RE.search(name or "")
    if m and _is_tag(m.group(1), tags):
        name = name[:m.start()]
    words = []
    for w in re.sub(r"[()（）]", " ", name or "").split():
        w = re.sub(r"^[\W_]+|[\W_]+$", "", w).casefold().replace("ё", "е")
        if w and not w.isdigit():
            words.append(w)
    return words


def namesake_index(names, tags: frozenset[str] = frozenset()) -> dict[str, list[str]]:
    """Слово имени (`name_words`) → многословные имена с этим словом.

    Порядок слов не важен: «Саша Образцов» и «Образцов Саша» оба лягут под «саша».
    Узел с местом в скобке («Илья (ОТДЕЛ)», «Иван (ИВАНОВ)») — отдельный человек, тёзка
    голого «Илья» (n611-s1-out3 Sonnet I2, Haiku I3). Метки диаризации в индекс не
    идут — за ними нет человека."""
    index: dict[str, list[str]] = {}
    for name in names:
        words = name_words(name, tags)
        tail = _LABEL_TAIL_RE.search(name)
        placed = bool(tail) and _is_place_tag(tail.group(1), tags)
        if (len(words) < 2 and not placed) or not words or is_placeholder_node(name):
            continue
        for w in dict.fromkeys(words):
            index.setdefault(w, []).append(name)
    return index


def bare_namesakes(name: str, index: dict[str, list[str]], *, owner: str,
                   tags: frozenset[str] = frozenset()) -> list[str]:
    """Голое имя с тёзками: однословное имя («Саша»), у которого среди живых узлов
    есть многословные с тем же словом («Саша Образцов», «Саша Сидоров») — их список,
    иначе пусто.

    `owner` — полное имя владельца, обязательно (пустая строка — владелец не
    известен): узел владельца тёзкой не считается, владелец в своём графе один.
    Узел владельца — все слова узла входят в имя владельца: «Пётр Лесков» при
    владельце «Пётр Иванович Лесков» (n611-s1-out2 Sonnet 7). Голый «Саша» при
    владельце «Саша Образцов» и живом «Саша Сидоров» — сборный: под ним владелец и
    другой человек (n611-s1-out1). Однословный владелец («Пётр» в конфиге): голый
    «Пётр» при живом «Пётр Лесков» — сборный по тому же правилу, модель отдаёт
    «Пётр» и владельцу, и тёзке (n611-s1-out3 Sonnet I1, DS I4; снятие узла в out2 —
    отменено).

    Под голым именем граф копит факты разных людей: каждый «Саша» встречи садится
    в один узел (№611, замер 27.10: 42 таких узла). Доктор считает по этому
    предикату; затвор на входе (№611 этап 2) будет решать по нему же. Имя с числом
    («Саша 2») — копия или метка, а не голое имя (n611-s1-out2 DS M3); имя с местом
    в скобке («Илья (ОТДЕЛ)») тёзок уже различает — не голое."""
    words = name_words(name, tags)
    tail = _LABEL_TAIL_RE.search(name)
    if (len(words) != 1 or is_placeholder_node(name) or (tail and _is_place_tag(tail.group(1), tags))
            or any(w.isdigit() for w in re.sub(r"[()（）]", " ", name).split())):
        return []
    own = set(name_words(owner))
    return sorted(n for n in index.get(words[0], [])
                  if not (len(own) >= 2 and set(name_words(n, tags)) <= own))


def is_collective(name: str, index: dict[str, list[str]], *, owner: str,
                  tags: frozenset[str] = frozenset()) -> bool:
    """Сборное имя: голое, и среди живых есть хоть один многословный тёзка.

    Один порог на доктора (счёт сборных узлов) и на затвор встречи в
    `graph_updater` (имя не пишется в узел): порог «≥ 2» у затвора при «≥ 1» у
    доктора оставлял 15 из 42 сборных копить ссылки (n611-in3 Sonnet C2 / DS C1)."""
    return bool(bare_namesakes(name, index, owner=owner, tags=tags))


def strip_speaker_label(name: str) -> str:
    """«Саша (Спикер 1)» → «Саша»: метка диаризации в скобках у настоящего
    имени — пометка модели, не часть имени.

    Фильтр `is_speaker_placeholder` снимает только хвостовую скобку и судит
    остаток: «Саша (Спикер 1)» проходил как человек «Саша (Спикер 1)» и
    получал узел-склейщик с меткой в имени (GLM, аудит памяти 07.09) — ровно
    те четыре узла, что doctor показывал после миграции №125. Имя-метка
    целиком («Собеседник 2 (Саша)») не трогается: его отсеет
    `is_speaker_placeholder`, а человек в скобках — догадка облака, не факт."""
    m = _LABEL_TAIL_RE.search(name or "")
    if not m or not is_label_tag(m.group(1)):
        return name
    bare = name[:m.start()].strip()
    return bare if bare and not is_speaker_placeholder(bare) else name
