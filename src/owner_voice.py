"""Чьи это слова: владельца или собеседника — решает КАНАЛ захвата.

Микрофон — аппаратный вход владельца, системный звук — то, что говорят
удалённые собеседники. Это не догадка о голосе, а устройство записи, и
именно этим подход отличается от провала 20.07, когда владельца пытались
угадать ВНУТРИ микрофонного канала: «первый голос» ловил лектора из видео,
«доминирование» ошибалось тоже.

Опираться на канал напрямую всё же нельзя — есть три дыры, и все три
закрываются здесь:

1. **Очная встреча.** Динамик молчит, в микрофон говорят все, кто в
   комнате. Различать некого — имя не ставится никому. Признак звонка:
   системный канал хоть раз нёс речь.
2. **Эхо.** Голос собеседника из динамиков попадает в микрофон.
   Подавление в `audio.py` глушит одновременную речь, но не тихий чанк и
   не длинную реверберацию. Второй эшелон здесь: голос, который слышен и
   в системном канале, владельцем быть не может. Центроиды у трекера
   общие для обоих каналов, поэтому эхо получает тот же номер голоса, что
   и оригинал.
3. **Гибрид.** Владелец в комнате не один: коллега рядом попадает в тот же
   микрофон. Это не закрывается: в звонке все голоса микрофона, кроме эха,
   подписываются владельцем — и в живой ленте, и в пересборке после «Стоп»
   (одно правило, `owner_voices`). Слова коллеги уходят под имя владельца;
   различать голоса внутри микрофона — задача слепка голоса владельца (№136),
   а не доли речи.

Счётчики живут в памяти встречи и умирают вместе с процессом: секунды речи
по номеру голоса — это производное от голоса, и обещание «ничего
голосового на диск» распространяется и на них.
"""
from __future__ import annotations

import dataclasses
import math
import re

#: Сколько секунд речи людей в микрофоне нужно накопить, прежде чем
#: подписывать владельца: случайный кашель и пара слов — шум, а не встреча.
MIN_MIC_SECONDS = 15.0

#: Сколько речи в системном канале достаточно, чтобы счесть голос чужим.
#: Не ноль: короткий всплеск может быть шумом нарезки, а не голосом.
ECHO_SECONDS = 1.0

#: Префикс нейтральных меток. Их генерируют В ТРЁХ местах (демон, живая
#: пересборка, офлайн), и до этой константы правильность гварда держалась на
#: совпадении трёх независимых литералов: поменяй метку канала — и живой
#: гвард молча перестал бы ловить «Собеседник N», а офлайн продолжил бы
#: (ревью 19.08, четвёртый круг).
NEUTRAL_BASE = "Собеседник"

#: Окно живых счётчиков секунд по голосу. Экспоненциальное затухание:
#: формат встречи меняется по ходу (коллега подсел, ушёл), и счёт обязан
#: следовать за этим, а не за первыми минутами.
WINDOW_S = 180.0

#: Текстовое эхо: сколько секунд помним недавние реплики каждого канала.
#: Эхо в микрофон и оригинал в системный канал распознаются в соседних
#: чанках — окна в полминуты хватает с запасом.
TEXT_ECHO_WINDOW_S = 30.0
#: Совпадение слов, начиная с которого фраза микрофона считается эхом
#: реплики из динамиков. Доля — от КОРОТКОЙ из двух фраз: STT режет края
#: эха, и требовать полное равенство значит не поймать ничего.
TEXT_ECHO_OVERLAP = 0.8
#: Минимум слов в короткой фразе пары: «да», «ага, понял» совпадают у всех
#: участников постоянно — это не эхо, а живая речь. 5, а не 4: у 4-словных
#: ритуальных формул («всем спасибо за участие») порог 0.8 означал полное
#: равенство — и они его давали (круг-1 по PR #401, DS+GLM).
TEXT_ECHO_MIN_WORDS = 5

#: Насколько эхо может отстоять от оригинала. Акустическое эхо синхронно
#: (секунды на границы чанков), цитата и согласие запаздывают на десятки
#: секунд — узкое окно ПАРЫ отделяет одно от другого; буфер
#: TEXT_ECHO_WINDOW_S остаётся широким ради обратного порядка распознавания
#: (круг-1 по PR #401, GLM).
TEXT_ECHO_PAIR_S = 8.0

def norm_words(text: str) -> tuple[str, ...]:
    """Слова фразы для сверки эха: нижний регистр, ё=е, только буквы.

    Числа выброшены: время, даты и номера — общий словарь обоих каналов,
    лишняя поверхность ложных совпадений (круг-1 по PR #401, DS).
    """
    out = []
    for raw in text.lower().replace("ё", "е").split():
        w = "".join(ch for ch in raw if ch.isalpha())
        if w:
            out.append(w)
    return tuple(out)


def text_echo_match(a: tuple[str, ...], b: tuple[str, ...]) -> bool:
    """Одна ли это фраза в двух каналах — по пересечению слов.

    Знаменатель — УНИКАЛЬНЫЕ слова короткой стороны, как и числитель:
    повторы («ладно, ладно, давайте…») поднимали фактический порог выше
    заявленного, и точная копия фразы могла не сматчиться (круг-1, GLM).
    """
    sa, sb = set(a), set(b)
    short = min(len(sa), len(sb))
    # Минимум — тоже по УНИКАЛЬНЫМ словам: «спасибо»×5 — это одно слово,
    # а не пять, и с уникальным знаменателем оно матчилось бы с любой
    # фразой, где есть «спасибо» (круг-3, DS).
    if short < TEXT_ECHO_MIN_WORDS:
        return False
    return len(sa & sb) / short >= TEXT_ECHO_OVERLAP


@dataclasses.dataclass
class Heard:
    """Сколько речи каждый голос дал в каждый канал — в пределах встречи.

    На диск не попадает и в сериализуемые объекты не кладётся.
    """
    mic: dict[int, float] = dataclasses.field(default_factory=dict)
    bh: dict[int, float] = dataclasses.field(default_factory=dict)
    #: Нёс ли системный канал речь хоть раз: признак звонка.
    call: bool = False
    #: Порог накопления уже взят: дальше владелец подписывается без него.
    #: Счётчики тают по WINDOW_S, и после паузы сумма опускалась ниже 15
    #: секунд — метка гасла и загоралась снова, мигая посреди встречи.
    owner_ready: bool = False
    #: Голоса, хоть раз прозвучавшие в системном канале дольше ECHO_SECONDS.
    #: Множество ЛИПКОЕ и затуханию не подлежит: счётчики bh тают по WINDOW_S,
    #: и после нескольких минут молчания бывшее эхо опускалось ниже порога —
    #: голос собеседника, попавший в микрофон через динамики, становился
    #: «владельцем», и его реплики уходили под именем хозяина встречи
    #: (ревью 20.08, локальная голова).
    echoed: set[int] = dataclasses.field(default_factory=set)
    #: Голоса, чья речь хоть раз дошла до стенограммы из канала собеседников и из
    #: микрофона. Липкие, как `echoed`, но без порога: это счёт голосов по каналам
    #: для сайдкара (`speakers_call`, `speakers_mic` — подсказки числа голосов
    #: пересборке, №573). Затухающие `bh` и `mic` не годятся — к «Стоп» они
    #: теряют затихших.
    bh_voices: set[int] = dataclasses.field(default_factory=set)
    mic_voices: set[int] = dataclasses.field(default_factory=set)
    #: Момент последнего затухания. Именно None, а не 0.0: нулевая отметка
    #: времени — законное значение (тесты, монотонные часы с нуля), и
    #: `if not self._last` съедал бы первое затухание молча.
    _last: float | None = None
    #: Недавние фразы каналов для ТЕКСТОВОЙ сверки эха (№93, 24.08: сверка
    #: по voice id слепа — live-трекер размечает каналы независимо, и id
    #: эха в микрофоне не совпадает с id собеседника в динамиках; текст
    #: одной фразы совпадает в обоих каналах независимо от id). Только в
    #: памяти процесса, на диск не попадает, окно TEXT_ECHO_WINDOW_S.
    _mic_texts: list[tuple[float, int | None, tuple[str, ...]]] = \
        dataclasses.field(default_factory=list)
    _bh_texts: list[tuple[float, tuple[str, ...]]] = \
        dataclasses.field(default_factory=list)
    #: Счёт текстовых пар на голос — ТОЛЬКО телеметрия для owner-pulse.
    _text_hits: dict[int, int] = dataclasses.field(default_factory=dict)

    def note(self, voice: int | None, seconds: float, *, is_mic: bool,
             now: float | None = None) -> None:
        """Отметить кусок речи. `voice=None` — трекер не определился."""
        if not is_mic:
            self.call = True
        if voice is None or seconds <= 0:
            return
        if now is not None:
            self._decay(now)
        acc = self.mic if is_mic else self.bh
        acc[voice] = acc.get(voice, 0.0) + seconds
        (self.mic_voices if is_mic else self.bh_voices).add(voice)
        if not is_mic and acc[voice] > ECHO_SECONDS:
            self.echoed.add(voice)      # раз собеседник — навсегда собеседник

    def _text_hit(self, voice: int | None) -> None:
        """Зачесть текстовое совпадение голосу — ТОЛЬКО телеметрия.

        В `echoed` текстовый путь НЕ пишет. Два круга по PR #401 (DS,
        Codex, GLM) показали: любой гвард дыряв с одной из сторон времени
        — до owner_ready ранний readback банил владельца навсегда, после
        owner_ready гвард накрывал и свежие эхо-id, глуша саму фичу; а
        счёт «2 хитов» засчитывал один пересказ дважды (STT режет фразу).
        По правилу «упрощать, а не латать» боевое влияние выключено:
        счётчики пар уходят в owner-pulse, включение пометки — отдельным
        решением по полевым данным нескольких встреч.
        """
        if voice is None:
            return
        self._text_hits[voice] = self._text_hits.get(voice, 0) + 1

    def note_text(self, voice: int | None, text: str, *, is_mic: bool,
                  now: float) -> bool:
        """Сверить фразу с недавними фразами ДРУГОГО канала.

        Совпадение в узком окне пары зачитывается голосу микрофона в
        ТЕЛЕМЕТРИЮ (_text_hits → owner-pulse); на подпись текст пока не
        влияет — см. _text_hit. Порядок распознавания каналов неизвестен —
        эхо в микрофоне может прийти и раньше оригинала, поэтому помним
        обе стороны и сверяем в обе (№93).
        """
        words = norm_words(text)
        if len(set(words)) < TEXT_ECHO_MIN_WORDS:
            return False
        fresh = now - TEXT_ECHO_WINDOW_S
        self._mic_texts = [x for x in self._mic_texts if x[0] >= fresh]
        self._bh_texts = [x for x in self._bh_texts if x[0] >= fresh]
        matched = False
        if is_mic:
            for bh_t, bh_words in self._bh_texts:
                if abs(now - bh_t) <= TEXT_ECHO_PAIR_S \
                        and text_echo_match(words, bh_words):
                    matched = True
                    self._text_hit(voice)
                    break
            if not matched:
                self._mic_texts.append((now, voice, words))
        else:
            # Один зачёт на bh-фразу (первое совпадение): счёт «на каждый
            # mic-кусок» делал text_pairs зависимым от порядка прихода и
            # нарезки STT — телеметрия становилась неинтерпретируемой
            # (круг-3, DS; симметрично mic-ветке).
            for mic_t, mic_voice, mic_words in self._mic_texts:
                if abs(now - mic_t) <= TEXT_ECHO_PAIR_S \
                        and text_echo_match(words, mic_words):
                    matched = True
                    self._text_hit(mic_voice)
                    break
            self._bh_texts.append((now, words))
        return matched

    def _decay(self, now: float) -> None:
        if self._last is None:
            self._last = now
            return
        dt = now - self._last
        if dt <= 0:
            return
        self._last = now
        factor = math.exp(-dt / WINDOW_S)
        for acc in (self.mic, self.bh):
            for voice in list(acc):
                acc[voice] *= factor
                if acc[voice] < 0.01:       # осевший до нуля голос не держим
                    del acc[voice]


def human_seconds(heard: Heard, *, echo_seconds: float = ECHO_SECONDS) -> float:
    """Сколько в микрофоне речи ЛЮДЕЙ — без эха из динамиков.

    Ровно та величина, с которой `owner_voices` сверяет порог
    `MIN_MIC_SECONDS`. Отдельной функцией потому, что по ней же демон решает, говорить ли человеку «в микрофоне
    слышно несколько человек»: считая эхо, он сообщал это в звонке, где
    второй «человек» — колонки владельца (ревью 19.08, третий круг).
    """
    return sum(s for v, s in heard.mic.items() if not is_echo(heard, v, echo_seconds))


def is_echo(heard: Heard, voice: int, echo_seconds: float = ECHO_SECONDS) -> bool:
    """Голос из микрофона — эхо собеседника: липко (хоть раз звучал в динамиках
    дольше порога) или прямо сейчас слышен в системном канале. Один предикат на
    human_seconds и owner_voices: копии условия в файле, чья история —
    рассинхрон живого и офлайна, уже расходились (критика GLM r1 по #555).

    В пересборке после «Стоп» `Heard` собирается без системного канала, и
    предикат ничего не отсекает: эхо там снимает геометрия — отрезок
    микрофона, накрытый речью собеседников больше чем наполовину
    (`rebuild_transcript.resolve_channel_segments`)."""
    return voice in heard.echoed or heard.bh.get(voice, 0.0) > echo_seconds


def owner_voices(heard: Heard, *, min_seconds: float = MIN_MIC_SECONDS,
                 echo_seconds: float = ECHO_SECONDS) -> set[int]:
    """Голоса владельца в ЗВОНКЕ — все микрофонные, кроме эха.

    В удалённой встрече микрофон несёт одного человека: собеседники приходят
    системным каналом. Требовать, чтобы один голос набрал 60% микрофонной
    речи, здесь нечего — дробление на «Собеседника 1» и «Собеседника 7» это
    артефакт лёгкого live-трекера, а не второй человек в комнате. Ровно из-за
    него живая стенограмма 20.08 не подписала владельца ни разу, хотя офлайн
    после «Стоп» опознал его уверенно (замер: 7 меток в live против имени в
    финале).

    Очных встреч правило не касается: там `call` не взводится, и метки
    остаются нейтральными.

    Правило одно для живой ленты и пересборки после «Стоп» (№509): раньше
    пересборка выбирала один голос по доле (60 % и отрыв 15 пунктов) и на
    звонке, где микрофон разметился на несколько меток, не подписывала
    владельца вовсе — финал переписывал живое имя на «Собеседник N».

    ⚠️ Цена третья, только в пересборке: эхо, которое геометрический фильтр
    не снял (отрезок микрофона накрыт речью собеседников наполовину или
    меньше), тоже уходит под имя владельца. Раньше оно оставалось нейтральным.

    ⚠️ Цена вторая: устойчивая ФОНОВАЯ речь в комнате (телевизор, радио,
    видео) копит секунды наравне с владельцем — счётчики питаются
    распознанным текстом, и после порога такой голос тоже подпишется его
    именем. Старое правило доли отсекало оба голоса разом; новое подписывает
    оба (ревью 20.08, DeepSeek).

    ⚠️ Цена первая — ГИБРИДНАЯ встреча: если рядом с владельцем у того же
    микрофона говорит коллега, его слова уйдут под именем владельца. Это
    осознанный размен: продукт рассчитан на удалённые встречи (решение
    владельца 20.08 — «очные встречи не нужны»).
    """
    if not heard.call:
        return set()
    mine = {v: s for v, s in heard.mic.items() if not is_echo(heard, v, echo_seconds)}
    if not heard.owner_ready:
        if sum(mine.values()) < min_seconds:
            return set()    # речи ещё мало: случайный кашель не подписываем
        heard.owner_ready = True
    return set(mine)


def collides_with_neutral(owner_label: str, other_label: str = NEUTRAL_BASE) -> bool:
    """Имя владельца неотличимо от нейтральной метки?

    Нейтральные метки генерируются С НОМЕРОМ («Собеседник 1», «Собеседник
    2»), поэтому проверять одно лишь равенство с `other_label` мало:
    человек, написавший в настройках «Собеседник 2», получил бы две разные
    физические метки с одним текстом. В стенограмме по метке склеиваются
    абзацы, а в пересборке по ней же выбирается дорожка для распознавания —
    и реплики удалённого собеседника поехали бы из микрофонного аудио
    (ревью 19.08, третий круг).
    """
    if not owner_label:
        return True
    if owner_label == other_label:
        return True
    return is_neutral_label(owner_label)


def is_neutral_label(label: str) -> bool:
    """Форма нейтральной метки: «Собеседник» или «Собеседник N».

    ЕДИНСТВЕННЫЙ предикат этой формы — раньше он жил тремя копиями
    (` ?\\d+` здесь, `\\s+\\d+` в скоринге пересборки, опциональный номер в
    перештамповке), и щель между ними возвращала №147 для имени владельца
    с экзотическим пробелом («Собеседник\u00a02» — GLM M2 по #465).
    База — НЕ параметр, а константа: нумерованные метки генерируются от
    неё независимо от того, как названы каналы.
    """
    # \s* (не \s+): «Собеседник2» слитно — тоже коллизия; сужение гварда
    # уже возвращало эту дыру (ревью 19.08, третий круг — тест это пинует).
    return bool(re.fullmatch(rf"{re.escape(NEUTRAL_BASE)}(?:\s*\d+)?", label))


def label_for(voice: int | None, *, is_mic: bool, heard: Heard,
              owner_label: str, other_label: str, neutral: str) -> str:
    """Метка для куска речи.

    `owner_label` — метка микрофонного канала (имя из настроек), `other_label`
    — метка системного, `neutral` — нейтральное «Собеседник N» от трекера.

    Имя, неотличимое от нейтральной метки, делает признак канала
    бессмысленным — тогда владельца не подписываем вовсе.

    Гистерезиса «решение принято — держим» здесь нет: множество голосов
    владельца липкое — оно только растёт по мере накопления речи
    (`owner_ready`), и мигать метке нечем.
    """
    if not is_mic or collides_with_neutral(owner_label, other_label):
        return neutral
    if voice is None:
        return neutral
    return owner_label if voice in owner_voices(heard) else neutral
