"""Чьи это слова: владельца или собеседника — решает КАНАЛ захвата.

Микрофон — аппаратный вход владельца, системный звук — то, что говорят
удалённые собеседники. Это не догадка о голосе, а устройство записи, и
именно этим подход отличается от провала 20.07, когда владельца пытались
угадать ВНУТРИ микрофонного канала: «первый голос» ловил лектора из видео,
«доминирование» ошибалось тоже.

Опираться на канал напрямую всё же нельзя — есть три дыры, и все три
закрываются здесь:

1. **Очная встреча.** Динамик молчит, в микрофон говорят все, кто в
   комнате. Различать некого — имя не ставится никому. Признак звонка:
   системный канал хоть раз нёс речь.
2. **Эхо.** Голос собеседника из динамиков попадает в микрофон.
   Подавление в `audio.py` глушит одновременную речь, но не тихий чанк и
   не длинную реверберацию. Второй эшелон здесь: голос, который слышен и
   в системном канале, владельцем быть не может. Центроиды у трекера
   общие для обоих каналов, поэтому эхо получает тот же номер голоса, что
   и оригинал.
3. **Гибрид.** Владелец в комнате не один: коллега рядом попадает в тот же
   микрофон. Имя ставится только тому голосу, который в микрофоне явно
   преобладает; нет преобладания — все остаются нейтральными.

Счётчики живут в памяти встречи и умирают вместе с процессом: секунды речи
по номеру голоса — это производное от голоса, и обещание «ничего
голосового на диск» распространяется и на них.
"""
from __future__ import annotations

import dataclasses
import math
import re

#: Сколько секунд речи в микрофоне нужно накопить, прежде чем вообще решать.
#: На двух фразах «преобладание» — это шум, а не факт.
MIN_MIC_SECONDS = 15.0

#: Какую долю микрофонной речи обязан занимать голос владельца.
MIN_SHARE = 0.6

#: И насколько он должен опережать второго. Без отрыва два собеседника
#: в комнате по очереди становились бы «владельцем».
MIN_LEAD = 0.15

#: Сколько речи в системном канале достаточно, чтобы счесть голос чужим.
#: Не ноль: короткий всплеск может быть шумом нарезки, а не голосом.
ECHO_SECONDS = 1.0

#: Префикс нейтральных меток. Их генерируют В ТРЁХ местах (демон, живая
#: пересборка, офлайн), и до этой константы правильность гварда держалась на
#: совпадении трёх независимых литералов: поменяй метку канала — и живой
#: гвард молча перестал бы ловить «Собеседник N», а офлайн продолжил бы
#: (ревью 19.08, четвёртый круг).
NEUTRAL_BASE = "Собеседник"

#: Окно, за которое считается преобладание. Экспоненциальное затухание:
#: формат встречи меняется по ходу (коллега подсел, ушёл), и решение обязано
#: следовать за этим, а не за первыми минутами.
WINDOW_S = 180.0


@dataclasses.dataclass
class Heard:
    """Сколько речи каждый голос дал в каждый канал — в пределах встречи.

    На диск не попадает и в сериализуемые объекты не кладётся.
    """
    mic: dict[int, float] = dataclasses.field(default_factory=dict)
    bh: dict[int, float] = dataclasses.field(default_factory=dict)
    #: Нёс ли системный канал речь хоть раз: признак звонка.
    call: bool = False
    #: Порог накопления уже взят: дальше владелец подписывается без него.
    #: Счётчики тают по WINDOW_S, и после паузы сумма опускалась ниже 15
    #: секунд — метка гасла и загоралась снова, мигая посреди встречи.
    owner_ready: bool = False
    #: Голоса, хоть раз прозвучавшие в системном канале дольше ECHO_SECONDS.
    #: Множество ЛИПКОЕ и затуханию не подлежит: счётчики bh тают по WINDOW_S,
    #: и после нескольких минут молчания бывшее эхо опускалось ниже порога —
    #: голос собеседника, попавший в микрофон через динамики, становился
    #: «владельцем», и его реплики уходили под именем хозяина встречи
    #: (ревью 20.08, локальная голова).
    echoed: set[int] = dataclasses.field(default_factory=set)
    #: Момент последнего затухания. Именно None, а не 0.0: нулевая отметка
    #: времени — законное значение (тесты, монотонные часы с нуля), и
    #: `if not self._last` съедал бы первое затухание молча.
    _last: float | None = None

    def note(self, voice: int | None, seconds: float, *, is_mic: bool,
             now: float | None = None) -> None:
        """Отметить кусок речи. `voice=None` — трекер не определился."""
        if not is_mic:
            self.call = True
        if voice is None or seconds <= 0:
            return
        if now is not None:
            self._decay(now)
        acc = self.mic if is_mic else self.bh
        acc[voice] = acc.get(voice, 0.0) + seconds
        if not is_mic and acc[voice] > ECHO_SECONDS:
            self.echoed.add(voice)      # раз собеседник — навсегда собеседник

    def _decay(self, now: float) -> None:
        if self._last is None:
            self._last = now
            return
        dt = now - self._last
        if dt <= 0:
            return
        self._last = now
        factor = math.exp(-dt / WINDOW_S)
        for acc in (self.mic, self.bh):
            for voice in list(acc):
                acc[voice] *= factor
                if acc[voice] < 0.01:       # осевший до нуля голос не держим
                    del acc[voice]


#: Пока голос УЖЕ признан владельцем, отпускаем его мягче, чем брали. Без
#: этого доля, колеблющаяся около 0.6 (двое в комнате говорят почти поровну),
#: заставляла метку мигать кусок за куском: абзац рвался надвое, а на
#: нейтральном куске открывался гейт мгновенных ответов (ревью 19.08).
KEEP_SHARE = 0.5
KEEP_LEAD = 0.05


def human_seconds(heard: Heard, *, echo_seconds: float = ECHO_SECONDS) -> float:
    """Сколько в микрофоне речи ЛЮДЕЙ — без эха из динамиков.

    Ровно та величина, по которой решает `owner_voice`. Отдельной функцией
    потому, что по ней же демон решает, говорить ли человеку «в микрофоне
    слышно несколько человек»: считая эхо, он сообщал это в звонке, где
    второй «человек» — колонки владельца (ревью 19.08, третий круг).
    """
    return sum(s for v, s in heard.mic.items()
               if heard.bh.get(v, 0.0) <= echo_seconds)


def owner_voices(heard: Heard, *, min_seconds: float = MIN_MIC_SECONDS,
                 echo_seconds: float = ECHO_SECONDS) -> set[int]:
    """Голоса владельца в ЗВОНКЕ — все микрофонные, кроме эха.

    В удалённой встрече микрофон несёт одного человека: собеседники приходят
    системным каналом. Требовать, чтобы один голос набрал 60% микрофонной
    речи, здесь нечего — дробление на «Собеседника 1» и «Собеседника 7» это
    артефакт лёгкого live-трекера, а не второй человек в комнате. Ровно из-за
    него живая стенограмма 20.08 не подписала владельца ни разу, хотя офлайн
    после «Стоп» опознал его уверенно (замер: 7 меток в live против имени в
    финале).

    Очных встреч правило не касается: там `call` не взводится, и метки
    остаются нейтральными.

    Это ЖИВОЙ путь. Офлайн-пересборка после «Стоп» по-прежнему зовёт
    `owner_voice()` с долей и отрывом: там диаризация идёт по всей записи,
    метки устойчивы, и выбрать один голос можно честно. Два режима, а не два
    источника истины.

    ⚠️ Цена вторая: устойчивая ФОНОВАЯ речь в комнате (телевизор, радио,
    видео) копит секунды наравне с владельцем — счётчики питаются
    распознанным текстом, и после порога такой голос тоже подпишется его
    именем. Старое правило доли отсекало оба голоса разом; новое подписывает
    оба (ревью 20.08, DeepSeek).

    ⚠️ Цена первая — ГИБРИДНАЯ встреча: если рядом с владельцем у того же
    микрофона говорит коллега, его слова уйдут под именем владельца. Это
    осознанный размен: продукт рассчитан на удалённые встречи (решение
    владельца 20.08 — «очные встречи не нужны»).
    """
    if not heard.call:
        return set()
    mine = {v: s for v, s in heard.mic.items()
            if v not in heard.echoed and heard.bh.get(v, 0.0) <= echo_seconds}
    if not heard.owner_ready:
        if sum(mine.values()) < min_seconds:
            return set()    # речи ещё мало: случайный кашель не подписываем
        heard.owner_ready = True
    return set(mine)


def owner_voice(heard: Heard, *, min_seconds: float = MIN_MIC_SECONDS,
                min_share: float = MIN_SHARE, min_lead: float = MIN_LEAD,
                echo_seconds: float = ECHO_SECONDS,
                current: int | None = None) -> int | None:
    """Номер голоса владельца — или None, если решать не на чем.

    None здесь означает «оставить нейтральные метки», а не «ошибка». Цена
    ошибки несимметрична: приписать владельцу чужие слова хуже, чем не
    подписать его собственные, — неверная метка переписывает встречу задним
    числом, и минутки с графом наследуют её молча.
    """
    if not heard.call:
        return None                     # очная встреча: различать некого
    # Голоса, слышные и в системном канале, — это эхо собеседников.
    candidates = {v: s for v, s in heard.mic.items()
                  if heard.bh.get(v, 0.0) <= echo_seconds}
    if not candidates:
        return None
    # Доля считается от речи ЛЮДЕЙ в комнате, а не от всего, что попало в
    # микрофон. Раньше эхо сидело в знаменателе, и в звонке с громкими
    # динамиками владелец — единственный живой голос — не набирал 0.6 и
    # оставался неподписанным, а человеку сообщалось «в микрофоне слышно
    # несколько человек», хотя второй «человек» — его же колонки
    # (ревью 19.08, второй круг).
    total = sum(candidates.values())
    ranked = sorted(candidates.items(), key=lambda kv: -kv[1])
    voice, seconds = ranked[0]
    share = seconds / total
    second = ranked[1][1] / total if len(ranked) > 1 else 0.0
    if voice == current:
        # Решение уже принято — держим, пока перевес не развалился. Проверка
        # идёт ДО порога «накопилось речи»: счётчики затухают, и после
        # десятиминутной паузы владелец переставал быть подписанным, пока
        # заново не наговорит пятнадцать секунд (ревью 19.08, второй круг).
        if share >= KEEP_SHARE and share - second >= KEEP_LEAD:
            return voice
        return None
    if total < min_seconds:
        return None                     # для НОВОГО решения речи ещё мало
    if share < min_share or share - second < min_lead:
        return None                     # в микрофоне не один человек
    return voice


def collides_with_neutral(owner_label: str, other_label: str = NEUTRAL_BASE) -> bool:
    """Имя владельца неотличимо от нейтральной метки?

    Нейтральные метки генерируются С НОМЕРОМ («Собеседник 1», «Собеседник
    2»), поэтому проверять одно лишь равенство с `other_label` мало:
    человек, написавший в настройках «Собеседник 2», получил бы две разные
    физические метки с одним текстом. В стенограмме по метке склеиваются
    абзацы, а в пересборке по ней же выбирается дорожка для распознавания —
    и реплики удалённого собеседника поехали бы из микрофонного аудио
    (ревью 19.08, третий круг).
    """
    if not owner_label:
        return True
    if owner_label == other_label:
        return True
    # База — НЕ параметр, а константа: нумерованные метки генерируются от неё
    # независимо от того, как названы каналы.
    return bool(re.fullmatch(rf"{re.escape(NEUTRAL_BASE)} ?\d+", owner_label))


def label_for(voice: int | None, *, is_mic: bool, heard: Heard,
              owner_label: str, other_label: str, neutral: str) -> str:
    """Метка для куска речи.

    `owner_label` — метка микрофонного канала (имя из настроек), `other_label`
    — метка системного, `neutral` — нейтральное «Собеседник N» от трекера.

    Имя, неотличимое от нейтральной метки, делает признак канала
    бессмысленным — тогда владельца не подписываем вовсе.

    Параметра `current` здесь нет намеренно: гистерезис «решение принято —
    держим» нужен там, где владелец ОДИН голос и его перевес может
    развалиться, то есть в офлайн-пути `owner_voice()`. В живом множество
    голосов и так липкое — оно только растёт по мере накопления речи
    (ревью 20.08, локальная голова: параметр остался бы мёртвым).
    """
    if not is_mic or collides_with_neutral(owner_label, other_label):
        return neutral
    if voice is None:
        return neutral
    return owner_label if voice in owner_voices(heard) else neutral
