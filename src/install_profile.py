"""Профиль установки: что эта машина тянет, а что на ней выключено.

Модели выбираются по объёму памяти (`ModelPresetPolicy` в приложении), но
одних моделей мало: на восьмигигабайтной машине рядом с STT и системой не
живут все контуры сразу. Раньше об этом была только фраза в описании
пресета — «Граф знаний выключен», — а код всё равно запускал разбор после
каждой встречи. Обещание без выключателя — это не обещание.

Что именно выключать, решил бенч 19.08 (scripts/bench_extract.py, три
реальные встречи): разбор в узлы лёгкой моделью РАБОТАЕТ — qwen3.5:4b дала
31 решение, 30 ядер и 96% проверяемых цитат, больше, чем gemma4:12b. Правило
«ниже 16 ГБ граф выключен» отменено; на лёгком профиле выключаются
семантические контуры, которые держат рядом эмбеддер bge-m3 (+1.2 ГБ): ночная
ревизия ядер и флаг `deja_vu` (цикл дежавю удалён №775; флаг ждёт смыслового
допуска ядер на авто-⏮, этап 2 №776, и пока ничего не включает).

Здесь и живут выключатели. Значения читаются мягко: приложение пишет их в
config.yaml строкой в кавычках (`graph: "false"`), и строгая проверка
`is True` считала бы такую строку включённым флагом — ровно тот сюрприз, за
которым потом идут в код (тот же класс ошибки чинили в автостопе 18.08).

Приватность сюда не переезжает: облачные ключи остаются в src/privacy.py со
своей строгой семантикой «молчание конфига = нет».
"""
from __future__ import annotations

import graphs
import privacy

_FALSE = {"false", "no", "off", "0", "нет", "выкл"}
_TRUE = {"true", "yes", "on", "1", "да", "вкл"}


def _section(cfg) -> dict:
    """Секция `sufler` или пустая: пустой YAML (None), список вместо словаря и `sufler:` без
    значения — тоже конфиг, с которым точка входа обязана работать (круг 1 по коду №249, Opus C1:
    «Забыть» падало на пустом config.yaml до стирания)."""
    section = cfg.get("sufler") if isinstance(cfg, dict) else None
    return section if isinstance(section, dict) else {}


def flag(cfg: dict, key: str, default: bool = True) -> bool:
    """Булев ключ секции `sufler` с нормализацией строк и мусора."""
    value = _section(cfg).get(key, default)
    if isinstance(value, bool):
        return value
    if value is None:
        return default
    text = str(value).strip().lower()
    if text in _FALSE:
        return False
    if text in _TRUE:
        return True
    return default


def graph_enabled(cfg: dict) -> bool:
    """Собирать ли граф знаний после встречи (`sufler.graph`).

    Выключен — стенограмма, минутки и архив собираются как обычно, а разбор
    в узлы не запускается.

    Ненастроенная папка графа (`graph_dir: ""` — дефолт шаблона и законный
    режим «только расшифровка») считается выключенным графом. Иначе конвейер
    честно доходил до конца, не находил заметку — её некуда было положить —
    и ронял ГОТОВУЮ встречу в «ошибку обработки», а `retry_unfinished`
    повторял этот путь трижды (ревью 19.08, второй круг Gemini; в main
    поведение было таким же).

    То же и для НЕСУЩЕСТВУЮЩЕГО пути (`~/Vault/Работа`, когда `~/Vault` ещё
    нет: опечатка, iCloud не скачан, папку только планируют): graph_updater
    там выходит рано, заметки нет — и без этой проверки встреча снова падала
    бы в «ошибку» с тремя повторами (третий круг, DeepSeek). Проверяем
    РОДИТЕЛЯ, а не саму папку: граф на первом запуске создаётся, и требовать
    его существования значило бы не создать его никогда.
    """
    graph_dir = graphs.graph_dir(cfg)
    if graph_dir is None:
        return False
    if not graph_dir.parent.is_dir():
        return False
    return flag(cfg, "graph", True)


#: Модели, на которых второй проход замерен и включён по умолчанию (№822). Замер 27.10 — эталон из
#: 17 встреч, только `qwen3.6:35b-mlx`: покрытие решений 57–65 % → 77–82 %, +130–145 с модели на
#: встречу. На 27B и 4B польза не мерилась, а один проход там и так в 2–4 раза дольше (бенч 19.08:
#: 224 и 113 с против 57 с), — модель сюда только после своего замера.
SECOND_PASS_MEASURED_MODELS = frozenset({"qwen3.6:35b-mlx"})


def graph_second_pass_enabled(cfg: dict) -> bool:
    """Второй проход разбора встречи кусками помельче (`sufler.graph_second_pass`, №821).

    Замер 27.10 на эталоне из 17 встреч: проход кусками 6000 знаков поверх боевого (12000) поднял
    покрытие решений с 57–65 % до 77–82 % без роста брака ревизии, ценой +130–145 с модели на
    встречу. Цена — время модели, а не память: две-три минуты на каждую встречу.

    Явный ключ владельца решает всегда (`true`/`false` и их строковые формы через `flag`); пустое
    значение — «не задано», нераспознанное (`fasle`) — выключено, как до умолчания: опечатка в
    `false` не должна включать дорогой проход (n822-out3, Haiku I1). Без ключа — умолчание здесь, в демоне, а не посев в файл
    владельца (№822, финальный Opus): включено только там, где замерено, — локальная модель
    `llm.model` из `SECOND_PASS_MEASURED_MODELS` на Ollama и язык разбора `ru` или пустой. На
    mlx-server разбор идёт на `llm.mlx_model`, в облаке — на `llm.cloud_model`, а не на `llm.model`:
    замера там нет, умолчание выключено.
    Язык решает и graph_updater (порог склейки мерен на русском): явный `true` при en проход
    всё равно не запустит."""
    raw = _section(cfg).get("graph_second_pass")
    if raw is not None and str(raw).strip():
        return flag(cfg, "graph_second_pass", False)
    llm_section = cfg.get("llm") if isinstance(cfg, dict) else None
    model = llm_section.get("model") if isinstance(llm_section, dict) else None
    if str(model or "").strip() not in SECOND_PASS_MEASURED_MODELS or graph_language(cfg) != "ru":
        return False
    # Тот же выбор движка, что у клиента: `cloud` без разрешения работает на Ollama (llm.LLM).
    engine = privacy.llm_engine(cfg)
    return engine == "ollama" or (engine == "cloud" and not privacy.cloud_engine_active(cfg))


def graph_decision_merge_enabled(cfg: dict) -> bool:
    """Склейка повторов во всём списке решений разбора (`sufler.graph_decision_merge`, №824).

    Части разбора идут с нахлёстом, а минутки лежат в хвосте стенограммы и попадают в две части
    сразу: модель пересказывает одно решение разными словами, дословный `_dedup` их не видит.
    Замер 28.10 (шесть встреч, 25 лишних строк глазами): склейка 0,7/3 снимает 5 из 25 без
    единой ложной, на эталоне из 17 встреч покрытие −1…−2 группы из 133 (одна настоящая потеря).
    Модель не зовёт.

    Пустое значение — включено; явный ключ может выключить, нераспознанное значение тоже
    выключает (как у второго прохода: опечатка в `false` не должна оставлять склейку). Порог
    мерен только на русском — en, zh и любой другой язык не клеят даже с явным `true`."""
    if graph_language(cfg) != "ru":
        return False
    raw = _section(cfg).get("graph_decision_merge")
    if raw is not None and str(raw).strip():
        return flag(cfg, "graph_decision_merge", False)
    return True


def graph_language(cfg: dict) -> str:
    """Язык значений разбора встречи (`sufler.language`): точное значение, пустое — русский.

    Одно чтение на промпт разбора (`graph_updater._language`) и умолчание второго прохода —
    иначе умолчание включило бы проход, который разбор потом пропустит (n822-out3, Sonnet M2).
    Регион к тегу не разбирается: `en-US` здесь не en — как у минуток и архива
    (`meeting_archive._config_lang`, финальный Opus №822, I3). Единый разбор языка — долг №615."""
    return str(_section(cfg).get("language") or "ru").strip().lower() or "ru"


def deja_vu_enabled(cfg: dict) -> bool:
    """Эмбеддер bge-m3 на живой встрече (`sufler.deja_vu`). Цикл дежавю удалён
    (№775); флаг оставлен под смысловую проверку ядер на авто-⏮ (этап 2 №776)
    и пресеты приложения — до неё в демоне читателя нет."""
    return flag(cfg, "deja_vu", True)


def brain_enabled(cfg: dict) -> bool:
    """Запись во внешнюю память (`sufler.brain`) — сервер `127.0.0.1:8100`, который есть только
    у того, кто поставил его сам. Умолчание — выключено: у любой другой установки запись копила
    бы замок и долг на каждую встречу и печатала curl на несуществующий сервер (№249).

    Не флаг пресета: в `ModelPresetPolicy.configFlags` его не добавлять, иначе смена пресета
    перезапишет решение владельца. Стирание и переименование уже записанного флаг не гасит:
    факты отправленных встреч лежат на сервере, пока их не удалят вместе с ним."""
    return flag(cfg, "brain", False)


def brain_explicit(cfg: dict) -> bool:
    """Ключ `sufler.brain` задан явно и распознан как да или нет. Только тогда строка «внешняя
    память выключена» что-то значит для человека: у того, у кого её не было, она читалась бы как
    поломка, а `brain:` без значения или мусор — не «false» (круг 1 по коду №249, Opus M1)."""
    value = _section(cfg).get("brain")
    return isinstance(value, bool) or str(value).strip().lower() in _FALSE | _TRUE


def tier3_enabled(cfg: dict) -> bool:
    """Ревизия ядер после встречи (`sufler.tier3`) — тоже через bge-m3.

    Выключается вместе с флагом `deja_vu` (лёгкий профиль): без этого обещание «эмбеддер на лёгком
    профиле не живёт» ломается — ревизия поднимала bge-m3 после каждой
    встречи и держала его ещё час (ревью 19.08, DeepSeek).
    """
    return flag(cfg, "tier3", True)
