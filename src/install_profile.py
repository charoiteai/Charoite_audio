"""Профиль установки: что эта машина тянет, а что на ней выключено.

Модели выбираются по объёму памяти (`ModelPresetPolicy` в приложении), но
одних моделей мало: на восьмигигабайтной машине рядом с STT и системой не
живут все контуры сразу. Раньше об этом была только фраза в описании
пресета — «Граф знаний выключен», — а код всё равно запускал разбор после
каждой встречи. Обещание без выключателя — это не обещание.

Что именно выключать, решил бенч 19.08 (scripts/bench_extract.py, три
реальные встречи): разбор в узлы лёгкой моделью РАБОТАЕТ — qwen3.5:4b дала
31 решение, 30 ядер и 96% проверяемых цитат, больше, чем gemma4:12b. Правило
«ниже 16 ГБ граф выключен» отменено; на лёгком профиле выключаются
семантические контуры, которые держат рядом эмбеддер bge-m3 (+1.2 ГБ): живое
дежавю и ночная ревизия ядер.

Здесь и живут выключатели. Значения читаются мягко: приложение пишет их в
config.yaml строкой в кавычках (`graph: "false"`), и строгая проверка
`is True` считала бы такую строку включённым флагом — ровно тот сюрприз, за
которым потом идут в код (тот же класс ошибки чинили в автостопе 18.08).

Приватность сюда не переезжает: облачные ключи остаются в src/privacy.py со
своей строгой семантикой «молчание конфига = нет».
"""
from __future__ import annotations

_FALSE = {"false", "no", "off", "0", "нет", "выкл"}
_TRUE = {"true", "yes", "on", "1", "да", "вкл"}


def flag(cfg: dict, key: str, default: bool = True) -> bool:
    """Булев ключ секции `sufler` с нормализацией строк и мусора."""
    value = (cfg.get("sufler") or {}).get(key, default)
    if isinstance(value, bool):
        return value
    if value is None:
        return default
    text = str(value).strip().lower()
    if text in _FALSE:
        return False
    if text in _TRUE:
        return True
    return default


def graph_enabled(cfg: dict) -> bool:
    """Собирать ли граф знаний после встречи (`sufler.graph`).

    Выключен — стенограмма, минутки и архив собираются как обычно, а разбор
    в узлы не запускается: на лёгком профиле он не помог бы, а стоил бы
    минут работы модели и статуса «ошибка обработки» на каждой встрече.
    """
    return flag(cfg, "graph", True)


def deja_vu_enabled(cfg: dict) -> bool:
    """Семантическое «⏮ уже обсуждалось» (`sufler.deja_vu`) — держит bge-m3."""
    return flag(cfg, "deja_vu", True)


def tier3_enabled(cfg: dict) -> bool:
    """Ревизия ядер после встречи (`sufler.tier3`) — тоже через bge-m3.

    Выключается там же, где дежавю: без этого обещание «эмбеддер на лёгком
    профиле не живёт» ломается — ревизия поднимала bge-m3 после каждой
    встречи и держала его ещё час (ревью 19.08, DeepSeek).
    """
    return flag(cfg, "tier3", True)
